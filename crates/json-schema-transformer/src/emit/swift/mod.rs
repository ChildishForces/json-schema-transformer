static SUB_SCHEMA_COUNTER: AtomicUsize = AtomicUsize::new(0);

thread_local! {
    /// Per-file type prefix applied to $defs type names so that many generated
    /// files can be compiled into a single Swift module without collisions.
    static TYPE_PREFIX: RefCell<String> = const { RefCell::new(String::new()) };
}

/// Shared helper type names that appear in type signatures (so they cannot be
/// `private`) and must instead be prefixed per-file to avoid duplicate symbols
/// when compiling many generated files into one module.
const SIGNATURE_HELPER_TYPES: &[&str] = &[
    "EmailAddress",
    "HostnameString",
    "IPv4Address",
    "IPv6Address",
    "IPAddress",
    "TimeString",
    "DurationString",
    "Base64String",
    // The Validatable protocol appears in type-declaration position on every
    // generated type, so inline mode prefixes it per file like the wrappers.
    // No other generated identifier contains this substring.
    "Validatable",
    // AnyCodable appears in stored-property signatures and is emitted inline
    // (non-private) so single-file output is self-contained; prefixing keeps
    // many files batch-compilable into one module.
    "AnyCodable",
];

/// Inlined validation round-trip for manual object initializers. Not a
/// `validate()` call — a schema property named "validate" would shadow the
/// protocol method and break compilation. Mirrors the Validatable extension's
/// matched ISO-8601 encoder/decoder pair.
const MANUAL_INIT_ROUNDTRIP: &str = "        let __jstEncoder = JSONEncoder()\n        __jstEncoder.dateEncodingStrategy = .iso8601\n        let __jstDecoder = JSONDecoder()\n        __jstDecoder.dateDecodingStrategy = .iso8601\n        _ = try __jstDecoder.decode(Self.self, from: __jstEncoder.encode(self))";

pub struct SwiftEmitter;

impl Emitter for SwiftEmitter {
    fn extension(&self) -> &str {
        "swift"
    }

    fn emit_with_options(
        &self,
        converted: &ConvertedSchema,
        name: &str,
        options: &EmitOptions,
    ) -> String {
        self.emit_module(converted, name, options).0
    }

    fn emit_collecting(
        &self,
        converted: &ConvertedSchema,
        name: &str,
        options: &EmitOptions,
    ) -> (String, HelperSet) {
        self.emit_module(converted, name, options)
    }

    fn helpers_content_for(&self, needs: &HelperSet) -> Option<String> {
        if needs.is_empty() {
            return None;
        }
        let helpers = SwiftHelpers::from_helper_set(needs);
        let mut s = String::from(
            "// Generated by json-schema-transformer — shared runtime helpers\n// DO NOT EDIT — changes will be overwritten on regeneration\n\nimport Foundation\n\n",
        );
        // Validatable protocol before ValidationError and the format types:
        // every generated type in the collection conforms to it.
        if helpers.needs_validatable {
            s.push_str(VALIDATABLE_HELPER);
            s.push('\n');
        }
        // JstIssue/JstValidationError before the types that throw them
        // (internal visibility, unlike the per-file private inline copies).
        if helpers.needs_jst_error {
            s.push_str(&strip_top_level_private(JST_ERROR_HELPER));
            s.push('\n');
        }
        // ValidationError with the union of cases the collection throws
        // (internal visibility, unlike the per-file private inline enum).
        if helpers.needs_any() {
            s.push_str(&helpers.emit_validation_error(false));
            s.push('\n');
        }
        // Format wrapper types (already internal with clean names in source).
        // IPAddress depends on both IPv4Address and IPv6Address.
        if helpers.needs_email {
            s.push_str(EMAIL_ADDRESS_HELPER);
            s.push('\n');
        }
        if helpers.needs_hostname {
            s.push_str(HOSTNAME_HELPER);
            s.push('\n');
        }
        if helpers.needs_ipv4 || helpers.needs_ip {
            s.push_str(IPV4_ADDRESS_HELPER);
            s.push('\n');
        }
        if helpers.needs_ipv6 || helpers.needs_ip {
            s.push_str(IPV6_ADDRESS_HELPER);
            s.push('\n');
        }
        if helpers.needs_ip {
            s.push_str(IP_ADDRESS_HELPER);
            s.push('\n');
        }
        if helpers.needs_time {
            s.push_str(TIME_STRING_HELPER);
            s.push('\n');
        }
        if helpers.needs_duration {
            s.push_str(DURATION_STRING_HELPER);
            s.push('\n');
        }
        if helpers.needs_base64 {
            s.push_str(BASE64_STRING_HELPER);
            s.push('\n');
        }
        // _serializeAny and the JSI interpreter are file-private in inline
        // mode; the shared module-wide declarations drop the `private`.
        if helpers.needs_serialize_any {
            s.push_str(&strip_top_level_private(SERIALIZE_ANY_HELPER));
            s.push('\n');
        }
        if helpers.needs_any_codable {
            s.push_str(ANY_CODABLE_HELPER);
            s.push('\n');
        }
        if helpers.needs_interpreter {
            s.push_str(&strip_top_level_private(JSI_SWIFT_HELPER));
        }
        let trimmed = s.trim_end().to_string();
        Some(trimmed + "\n")
    }

    fn helpers_content(&self) -> Option<String> {
        let mut all = HelperSet::default();
        for n in [
            "validatable",
            "jst_error",
            "email",
            "hostname",
            "ipv4",
            "ipv6",
            "ip",
            "time",
            "duration",
            "base64",
            "numeric_validation",
            "serialize_any",
            "any_codable",
            "jsi",
        ] {
            all.insert(n);
        }
        self.helpers_content_for(&all)
    }

    fn default_helpers_file(&self) -> Option<&'static str> {
        Some("JstHelpers.swift")
    }
}

impl SwiftEmitter {
    fn emit_module(
        &self,
        converted: &ConvertedSchema,
        name: &str,
        options: &EmitOptions,
    ) -> (String, HelperSet) {
        // Reset global sub-schema counter for each emit
        SUB_SCHEMA_COUNTER.store(0, Ordering::Relaxed);
        // Root names hitting a reserved type name ("Validatable", "Error", …)
        // get the same "Schema" suffix as defs — a schema titled
        // "Validatable" must not collide with the protocol.
        let mut pascal = to_pascal_case(name);
        if SWIFT_RESERVED_TYPES.contains(&pascal.as_str()) {
            pascal = format!("{pascal}Schema");
        }
        // Prefix $defs type names per file so many files can share one module.
        TYPE_PREFIX.with(|p| *p.borrow_mut() = pascal.clone());
        let mut out = String::new();

        out.push_str(&format!(
            "// Generated by json-schema-transformer\n// {name}\n// DO NOT EDIT — changes will be overwritten on regeneration\n\n"
        ));
        out.push_str("import Foundation\n\n");

        // Emit body first to detect which helpers are needed
        let mut body = String::new();
        for def in &converted.defs {
            let safe_name = sanitize_swift_name(&def.name);
            let code = emit_struct(&safe_name, &def.schema, &converted.defs);
            // For recursive types, Swift structs can't form cycles — use class
            let code = if def.is_recursive {
                code.replacen(&format!("struct {safe_name}:"), &format!("final class {safe_name}:"), 1)
            } else {
                code
            };
            body.push_str(&code);
            body.push_str("\n\n");
        }
        body.push_str(&emit_struct(
            &pascal,
            &converted.root,
            &converted.defs,
        ));
        body.push('\n');

        // --mutable: stored properties become `var`. Member-level stored
        // properties are the only 4-space-indented `let` declarations the
        // emitter produces (locals inside init bodies are indented 8 spaces),
        // so a targeted textual rewrite keeps the emit call graph untouched.
        if options.mutable {
            body = body.replace("\n    let ", "\n    var ");
            // Interpreted roots store their value as `private let`.
            body = body.replace("\n    private let ", "\n    private var ");
        }

        // Detect which helpers this module references (drives inline emission
        // and the collection-mode needs report).
        let mut helpers = SwiftHelpers::default();
        helpers.detect(&body);

        // Collection mode: all utility helpers (ValidationError, format
        // wrapper types, _serializeAny, AnyCodable, the JSI interpreter) are
        // declared once, with internal visibility and clean names, in the
        // companion helpers file (see [`Emitter::helpers_content_for`]) and
        // compiled into the same module — nothing to inline and no per-file
        // prefixing of helper type names. $defs type prefixing (schema-specific
        // types) still applies via TYPE_PREFIX.
        if options.helpers.is_some() {
            out.push_str(&body);
            return (out, helpers.to_helper_set());
        }

        // Validatable protocol first — appended before the prefixing loop at
        // the end of this function so it gets the same per-file rename as the
        // conformance sites in the body.
        if helpers.needs_validatable {
            out.push_str(VALIDATABLE_HELPER);
            out.push('\n');
        }
        // JstIssue/JstValidationError: file-private (top-level `private`), so
        // many inline files can each carry a copy in one module.
        if helpers.needs_jst_error {
            out.push_str(JST_ERROR_HELPER);
            out.push('\n');
        }
        // Emit validation error enum if any validating types are used
        if helpers.needs_any() {
            out.push_str(&helpers.emit_validation_error(true));
            out.push('\n');
        }
        if helpers.needs_email {
            out.push_str(EMAIL_ADDRESS_HELPER);
            out.push('\n');
        }
        if helpers.needs_hostname {
            out.push_str(HOSTNAME_HELPER);
            out.push('\n');
        }
        if helpers.needs_ipv4 {
            out.push_str(IPV4_ADDRESS_HELPER);
            out.push('\n');
        }
        if helpers.needs_ipv6 {
            out.push_str(IPV6_ADDRESS_HELPER);
            out.push('\n');
        }
        if helpers.needs_ip {
            // IPAddress depends on IPv4Address and IPv6Address
            if !helpers.needs_ipv4 {
                out.push_str(IPV4_ADDRESS_HELPER);
                out.push('\n');
            }
            if !helpers.needs_ipv6 {
                out.push_str(IPV6_ADDRESS_HELPER);
                out.push('\n');
            }
            out.push_str(IP_ADDRESS_HELPER);
            out.push('\n');
        }
        if helpers.needs_time {
            out.push_str(TIME_STRING_HELPER);
            out.push('\n');
        }
        if helpers.needs_duration {
            out.push_str(DURATION_STRING_HELPER);
            out.push('\n');
        }
        if helpers.needs_base64 {
            out.push_str(BASE64_STRING_HELPER);
            out.push('\n');
        }
        if helpers.needs_serialize_any {
            out.push_str(SERIALIZE_ANY_HELPER);
            out.push('\n');
        }
        // AnyCodable appears in stored-property signatures, so it is emitted
        // non-private and per-file prefixed (SIGNATURE_HELPER_TYPES) — this
        // makes single-file output fully self-contained.
        if helpers.needs_any_codable {
            out.push_str(ANY_CODABLE_HELPER);
            out.push('\n');
        }
        if helpers.needs_interpreter {
            out.push_str(JSI_SWIFT_HELPER);
            out.push('\n');
        }

        out.push_str(&body);

        // Prefix signature-visible helper types (EmailAddress, TimeString, …)
        // per file: they appear in stored-property/typealias signatures of the
        // internal root type, so they cannot be `private` — renaming them keeps
        // every generated file safe to compile into one shared module.
        // (String literals are immune: swift_escape encodes helper-name
        // occurrences in schema strings with \u{...} escapes.) When the root
        // prefix itself contains the helper name, "{prefix}{helper}" would
        // rewrite the root type's own identifier — use a "Jst" prefix instead.
        let prefix = pascal.clone();
        for helper in SIGNATURE_HELPER_TYPES {
            if out.contains(helper) {
                let target = if prefix.contains(helper) {
                    format!("Jst{helper}")
                } else {
                    format!("{prefix}{helper}")
                };
                out = out.replace(helper, &target);
            }
        }
        (out, helpers.to_helper_set())
    }
}

/// Remove `private ` from top-level (column-0) declarations, turning
/// file-private helpers into internal ones for the shared helpers file.
/// Indented (member-level) `private` modifiers are left untouched.
fn strip_top_level_private(src: &str) -> String {
    let mut out: String = src
        .lines()
        .map(|line| line.strip_prefix("private ").unwrap_or(line))
        .collect::<Vec<_>>()
        .join("\n");
    if src.ends_with('\n') {
        out.push('\n');
    }
    out
}

// ── Helper detection ─────────────────────────────────────────────────────────

#[derive(Default)]
struct SwiftHelpers {
    needs_validatable: bool,
    needs_jst_error: bool,
    needs_email: bool,
    needs_hostname: bool,
    needs_ipv4: bool,
    needs_ipv6: bool,
    needs_ip: bool,
    needs_time: bool,
    needs_duration: bool,
    needs_base64: bool,
    needs_numeric_validation: bool,
    needs_serialize_any: bool,
    needs_any_codable: bool,
    needs_interpreter: bool,
}

impl SwiftHelpers {
    fn detect(&mut self, body: &str) {
        // Every generated struct/class/enum conforms; only typealias-only
        // modules skip the protocol.
        self.needs_validatable = body.contains("Validatable");
        // Every issue-collecting (or single-verdict JstValidationError-
        // throwing) init constructs a JstIssue.
        self.needs_jst_error = body.contains("JstIssue");
        self.needs_email = body.contains("EmailAddress");
        self.needs_hostname = body.contains("HostnameString");
        self.needs_ipv4 = body.contains("IPv4Address");
        self.needs_ipv6 = body.contains("IPv6Address");
        self.needs_ip = body.contains("IPAddress");
        self.needs_time = body.contains("TimeString");
        self.needs_duration = body.contains("DurationString");
        self.needs_base64 = body.contains("Base64String");
        self.needs_numeric_validation = body.contains("// @validate");
        self.needs_serialize_any = body.contains("_serializeAny");
        self.needs_any_codable = body.contains("AnyCodable");
        self.needs_interpreter = body.contains("JSIValidator");
    }

    fn to_helper_set(&self) -> HelperSet {
        let mut needs = HelperSet::default();
        let flags: [(&'static str, bool); 14] = [
            ("validatable", self.needs_validatable),
            ("jst_error", self.needs_jst_error),
            ("email", self.needs_email),
            ("hostname", self.needs_hostname),
            ("ipv4", self.needs_ipv4),
            ("ipv6", self.needs_ipv6),
            ("ip", self.needs_ip),
            ("time", self.needs_time),
            ("duration", self.needs_duration),
            ("base64", self.needs_base64),
            ("numeric_validation", self.needs_numeric_validation),
            ("serialize_any", self.needs_serialize_any),
            ("any_codable", self.needs_any_codable),
            ("jsi", self.needs_interpreter),
        ];
        for (key, on) in flags {
            if on {
                needs.insert(key);
            }
        }
        needs
    }

    fn from_helper_set(needs: &HelperSet) -> SwiftHelpers {
        SwiftHelpers {
            needs_validatable: needs.contains("validatable"),
            needs_jst_error: needs.contains("jst_error"),
            needs_email: needs.contains("email"),
            needs_hostname: needs.contains("hostname"),
            needs_ipv4: needs.contains("ipv4"),
            needs_ipv6: needs.contains("ipv6"),
            needs_ip: needs.contains("ip"),
            needs_time: needs.contains("time"),
            needs_duration: needs.contains("duration"),
            needs_base64: needs.contains("base64"),
            needs_numeric_validation: needs.contains("numeric_validation"),
            needs_serialize_any: needs.contains("serialize_any"),
            needs_any_codable: needs.contains("any_codable"),
            needs_interpreter: needs.contains("jsi"),
        }
    }

    fn needs_any(&self) -> bool {
        self.needs_email
            || self.needs_hostname
            || self.needs_ipv4
            || self.needs_ipv6
            || self.needs_ip
            || self.needs_time
            || self.needs_duration
            || self.needs_base64
            || self.needs_numeric_validation
    }

    fn emit_validation_error(&self, private: bool) -> String {
        let mut cases = Vec::new();
        let mut descriptions = Vec::new();

        if self.needs_email {
            cases.push("    case invalidEmail(String)");
            descriptions.push(r#"        case .invalidEmail(let v): "Invalid email address: \(v)""#);
        }
        if self.needs_hostname {
            cases.push("    case invalidHostname(String)");
            descriptions.push(r#"        case .invalidHostname(let v): "Invalid hostname: \(v)""#);
        }
        if self.needs_ipv4 || self.needs_ip {
            cases.push("    case invalidIPv4(String)");
            descriptions.push(r#"        case .invalidIPv4(let v): "Invalid IPv4 address: \(v)""#);
        }
        if self.needs_ipv6 || self.needs_ip {
            cases.push("    case invalidIPv6(String)");
            descriptions.push(r#"        case .invalidIPv6(let v): "Invalid IPv6 address: \(v)""#);
        }
        if self.needs_ip {
            cases.push("    case invalidIP(String)");
            descriptions.push(r#"        case .invalidIP(let v): "Invalid IP address: \(v)""#);
        }
        if self.needs_time {
            cases.push("    case invalidTime(String)");
            descriptions.push(r#"        case .invalidTime(let v): "Invalid time: \(v)""#);
        }
        if self.needs_duration {
            cases.push("    case invalidDuration(String)");
            descriptions.push(r#"        case .invalidDuration(let v): "Invalid duration: \(v)""#);
        }
        if self.needs_base64 {
            cases.push("    case invalidBase64(String)");
            descriptions.push(r#"        case .invalidBase64(let v): "Invalid base64: \(v)""#);
        }
        if self.needs_numeric_validation {
            cases.push("    case outOfRange(String, String)");
            descriptions.push(r#"        case .outOfRange(let field, let detail): "\(field): \(detail)""#);
        }

        format!(
            "{}enum ValidationError: LocalizedError {{\n{}\n\n    var errorDescription: String? {{\n        switch self {{\n{}\n        }}\n    }}\n}}\n",
            if private { "private " } else { "" },
            cases.join("\n"),
            descriptions.join("\n"),
        )
    }
}

