#[cfg(test)]
mod tests {
    use super::*;
    use crate::Converter;
    use serde_json::json;

    fn emit(schema: serde_json::Value) -> String {
        let converted = Converter::convert(&schema).unwrap();
        RustEmitter.emit_with_options(&converted, "sample", &EmitOptions::default())
    }

    fn emit_shared(schema: serde_json::Value) -> (String, HelperSet) {
        let converted = Converter::convert(&schema).unwrap();
        let options = EmitOptions {
            helpers: Some(super::super::SharedHelpers::new("jst_helpers.rs")),
            ..EmitOptions::default()
        };
        RustEmitter.emit_collecting(&converted, "sample", &options)
    }

    #[test]
    fn object_typed_struct() {
        let out = emit(json!({
            "type": "object",
            "properties": {
                "id": {"type": "string"},
                "qty": {"type": "integer"},
                "tags": {"type": "array", "items": {"type": "string"}}
            },
            "required": ["id", "qty"]
        }));
        assert!(out.contains("pub struct Sample {"), "{out}");
        assert!(out.contains("pub id: String"), "{out}");
        assert!(out.contains("pub qty: serde_json::Number"), "{out}");
        assert!(out.contains("pub tags: Option<Vec<String>>"), "{out}");
        assert!(out.contains("_jst_from_value"), "{out}");
    }

    #[test]
    fn integer_multiple_of_uses_num_helper() {
        let out = emit(json!({"type": "integer", "multipleOf": 0.5}));
        assert!(out.contains("_jst_multiple_of("), "{out}");
        assert!(out.contains("_jst_is_integer("), "{out}");
        // Inline mode appends the num helper snippet.
        assert!(out.contains("pub fn _jst_multiple_of"), "{out}");
    }

    #[test]
    fn unique_items_uses_canonical() {
        let out = emit(json!({"type": "array", "items": {"type": "number"}, "uniqueItems": true}));
        assert!(out.contains("_jst_canonical("), "{out}");
        assert!(out.contains("pub fn _jst_canonical"), "{out}");
    }

    #[test]
    fn const_object_uses_eq() {
        let out = emit(json!({"const": {"a": 1}}));
        assert!(out.contains("_jst_eq("), "{out}");
    }

    #[test]
    fn one_of_exactly_one() {
        let out = emit(json!({"oneOf": [
            {"type": "integer", "multipleOf": 5},
            {"type": "integer", "multipleOf": 3}
        ]}));
        assert!(out.contains("count() == 1"), "{out}");
        assert!(out.contains("pub struct Sample(pub serde_json::Value)"), "{out}");
    }

    #[test]
    fn string_enum_emits_rust_enum() {
        let out = emit(json!({"enum": ["red", "green-blue"]}));
        assert!(out.contains("pub enum Sample"), "{out}");
        assert!(out.contains("#[serde(rename = \"green-blue\")]"), "{out}");
    }

    #[test]
    fn recursive_ref_boxed() {
        let out = emit(json!({
            "$defs": {
                "node": {
                    "type": "object",
                    "properties": {
                        "value": {"type": "string"},
                        "next": {"$ref": "#/$defs/node"}
                    },
                    "required": ["value"]
                }
            },
            "$ref": "#/$defs/node"
        }));
        assert!(out.contains("Box<SampleNode>"), "{out}");
        assert!(out.contains("pub type Sample = SampleNode;"), "{out}");
    }

    #[test]
    fn keyword_field_renamed() {
        let out = emit(json!({
            "type": "object",
            "properties": {"type": {"type": "string"}},
            "required": ["type"]
        }));
        assert!(out.contains("pub r#type: String"), "{out}");
        assert!(out.contains("#[serde(rename = \"type\")]"), "{out}");
    }

    #[test]
    fn collection_mode_uses_shared_helpers() {
        let (out, needs) = emit_shared(json!({"const": {"a": 1}}));
        assert!(out.contains("use super::jst_helpers::*;"), "{out}");
        assert!(!out.contains("pub fn _jst_eq"), "{out}");
        assert!(needs.contains("eq"));
    }

    #[test]
    fn helpers_content_jsi_implies_eq() {
        let mut needs = HelperSet::default();
        needs.insert("jsi");
        let content = RustEmitter.helpers_content_for(&needs).unwrap();
        assert!(content.contains("pub fn _jst_eq"), "{content}");
        assert!(content.contains("pub fn _jst_jsi_validate"), "{content}");
    }

    #[test]
    fn format_maps_to_predicate() {
        let out = emit(json!({"type": "string", "format": "email"}));
        assert!(out.contains("_jst_is_email(s)"), "{out}");
        assert!(out.contains("pub fn _jst_is_email"), "{out}");
    }

    #[test]
    fn split_check_and_validate_methods() {
        let out = emit(json!({
            "type": "object",
            "properties": {"id": {"type": "string"}},
            "required": ["id"]
        }));
        assert!(out.contains("pub fn _jst_check"), "{out}");
        assert!(out.contains("pub fn validate"), "{out}");
        assert!(out.contains("pub fn to_validated_json"), "{out}");
        // _jst_from_value routes through _jst_check.
        assert!(out.contains("Self::_jst_check(v)?;"), "{out}");
    }

    #[test]
    fn enum_and_newtype_get_validate() {
        let e = emit(json!({"enum": ["red", "blue"]}));
        assert!(e.contains("pub fn _jst_check"), "{e}");
        assert!(e.contains("pub fn validate"), "{e}");
        assert!(e.contains("Self::_jst_check(v)?;"), "{e}");
        let n = emit(json!({"type": "string", "minLength": 1}));
        assert!(n.contains("pub fn _jst_check"), "{n}");
        assert!(n.contains("pub fn to_validated_json"), "{n}");
    }

    #[test]
    fn ref_check_recurses_into_jst_check() {
        let out = emit(json!({
            "$defs": {"node": {"type": "object", "properties": {"v": {"type": "string"}}, "required": ["v"]}},
            "type": "object",
            "properties": {"n": {"$ref": "#/$defs/node"}},
            "required": ["n"]
        }));
        assert!(out.contains("SampleNode::_jst_check("), "{out}");
    }

    #[test]
    fn mutable_flag_is_noop() {
        let schema = json!({
            "type": "object",
            "properties": {"id": {"type": "string"}},
            "required": ["id"]
        });
        let converted = Converter::convert(&schema).unwrap();
        let plain = RustEmitter.emit_with_options(&converted, "sample", &EmitOptions::default());
        let mutable = RustEmitter.emit_with_options(
            &converted,
            "sample",
            &EmitOptions {
                mutable: true,
                ..EmitOptions::default()
            },
        );
        assert_eq!(plain, mutable);
    }

    #[test]
    fn interpreted_embeds_schema() {
        let out = emit(json!({
            "type": "object",
            "properties": {"a": {"type": "string"}},
            "unevaluatedProperties": false
        }));
        assert!(out.contains("_jst_jsi_validate("), "{out}");
    }
}
