/// Emit a sub-schema as a named struct if it's complex, returning (preamble, type_name).
/// Emit a sub-schema as a named struct if it's complex, returning (preamble, type_name).
fn emit_swift_sub_schema(prefix: &str, ir: &SchemaIr, defs: &[DefEntry], _counter: &mut usize) -> (String, String) {
    // Unwrap modifiers
    let inner = unwrap_modifiers(ir);

    // Any (boolean true) — accepts everything, no wrapper needed
    if matches!(inner, SchemaIr::Any | SchemaIr::Unknown) {
        return (String::new(), "AnyCodable".to_string());
    }

    // Never needs a wrapper (Swift's Never type can't be decoded)
    if matches!(inner, SchemaIr::Never) {
        let idx = SUB_SCHEMA_COUNTER.fetch_add(1, Ordering::Relaxed) + 1;
        let sub_name = format!("_{prefix}{idx}");
        let def = format!(
            "private struct {sub_name}: Codable {{\n    // @validate\n    init(from decoder: Decoder) throws {{\n        throw ValidationError.outOfRange(\"value\", \"schema rejects all values\")\n    }}\n    func encode(to encoder: Encoder) throws {{}}\n}}"
        );
        return (format!("{def}\n\n"), sub_name);
    }

    let st = swift_type(ir, defs);

    // If the IR needs validation that swift_type alone can't express, emit a wrapper
    // This catches Literal(exact value), ConstEqual, MixedEnum, ComplexEnum, Not, Conditional,
    // TypeGuarded, constrained Integer/Number/String, constrained Array, etc.
    let needs_wrapper = match inner {
        SchemaIr::Literal(_) | SchemaIr::ConstEqual(_) | SchemaIr::ComplexEnum(_)
        | SchemaIr::MixedEnum(_) | SchemaIr::TypeGuarded(_) | SchemaIr::Not { .. }
        | SchemaIr::Conditional { .. } | SchemaIr::ExclusiveUnion(_)
        | SchemaIr::Object(_) | SchemaIr::Tuple(_) => true,
        SchemaIr::Integer(c) => c.minimum.is_some() || c.maximum.is_some()
            || c.exclusive_minimum.is_some() || c.exclusive_maximum.is_some()
            || c.multiple_of.is_some(),
        SchemaIr::Number(c) => c.minimum.is_some() || c.maximum.is_some()
            || c.exclusive_minimum.is_some() || c.exclusive_maximum.is_some()
            || c.multiple_of.is_some(),
        SchemaIr::String(c) => c.min_length.is_some() || c.max_length.is_some() || c.pattern.is_some(),
        SchemaIr::Boolean => true, // needs wrapper to reject non-bool
        SchemaIr::Null => true, // needs wrapper for null-only
        SchemaIr::Array(arr) => arr.min_items.is_some() || arr.max_items.is_some()
            || arr.unique_items || arr.contains.is_some()
            || !matches!(arr.items.as_ref(), SchemaIr::Any),
        SchemaIr::Intersection(members) if members.len() > 1 => true,
        SchemaIr::Intersection(members) if members.len() == 1 => {
            // Delegate to single member — handled via recursive call below
            return emit_swift_sub_schema(prefix, &members[0], defs, _counter);
        }
        SchemaIr::Union(members) if members.len() > 1 => st == "AnyCodable",
        SchemaIr::Enum(cases) if cases.is_empty() => true,
        _ => st == "AnyCodable",
    };

    if needs_wrapper {
        let idx = SUB_SCHEMA_COUNTER.fetch_add(1, Ordering::Relaxed) + 1;
        let sub_name = format!("_{prefix}{idx}");
        let def = privatize_decl(emit_wrapper_struct(&sub_name, inner, defs), &sub_name);
        return (format!("{def}\n\n"), sub_name);
    }

    // If swift_type gives us a real named type, use it directly
    if st != "AnyCodable" {
        return (String::new(), st);
    }
    // Need to emit a named wrapper struct
    let idx = SUB_SCHEMA_COUNTER.fetch_add(1, Ordering::Relaxed) + 1;
    let sub_name = format!("_{prefix}{idx}");
    let def = privatize_decl(emit_wrapper_struct(&sub_name, ir, defs), &sub_name);
    (format!("{def}\n\n"), sub_name)
}

fn emit_not_wrapper(name: &str, _base: &SchemaIr, not_schema: &SchemaIr, defs: &[DefEntry]) -> String {
    let mut counter = 0usize;
    let (preamble, not_type) = emit_swift_sub_schema("Not", not_schema, defs, &mut counter);
    let body = format!(
        "struct {name}: Codable {{\n    let value: AnyCodable\n\n    // @validate\n    init(from decoder: Decoder) throws {{\n        let container = try decoder.singleValueContainer()\n        let raw = try container.decode(AnyCodable.self)\n        value = raw\n        let data = _serializeAny(raw.value)\n        if (try? JSONDecoder().decode({not_type}.self, from: data)) != nil {{\n            throw ValidationError.outOfRange(\"value\", \"must not match excluded schema\")\n        }}\n    }}\n\n    func encode(to encoder: Encoder) throws {{\n        var container = encoder.singleValueContainer()\n        try container.encode(value)\n    }}\n}}"
    );
    format!("{preamble}{body}")
}

