fn emit_nested_enum(name: &str, cases: &[String]) -> String {
    let mut lines = vec![format!("    enum {name}: String, Codable {{")];
    for case in cases {
        let swift_case = to_camel_case(case);
        if swift_case != *case {
            lines.push(format!(
                "        case {swift_case} = \"{}\"",
                swift_escape(case)
            ));
        } else {
            lines.push(format!("        case {swift_case}"));
        }
    }
    lines.push("    }".to_string());
    lines.join("\n")
}

fn swift_type(ir: &SchemaIr, defs: &[DefEntry]) -> String {
    match ir {
        SchemaIr::String(c) => match &c.format {
            Some(StringFormat::Email) => "EmailAddress".to_string(),
            Some(StringFormat::DateTime) => "Date".to_string(),
            Some(StringFormat::Date) => "Date".to_string(),
            Some(StringFormat::Time) => "TimeString".to_string(),
            Some(StringFormat::Uri) => "URL".to_string(),
            Some(StringFormat::Uuid) => "UUID".to_string(),
            Some(StringFormat::Ip) => "IPAddress".to_string(),
            Some(StringFormat::Ipv4) => "IPv4Address".to_string(),
            Some(StringFormat::Ipv6) => "IPv6Address".to_string(),
            Some(StringFormat::Hostname) => "HostnameString".to_string(),
            Some(StringFormat::Duration) => "DurationString".to_string(),
            Some(StringFormat::Base64) => "Base64String".to_string(),
            None => "String".to_string(),
        },
        SchemaIr::Number(_) => "Double".to_string(),
        SchemaIr::Integer(_) => "Int".to_string(),
        SchemaIr::Boolean => "Bool".to_string(),
        SchemaIr::Null => "Never?".to_string(),
        SchemaIr::Any | SchemaIr::Unknown => "AnyCodable".to_string(),
        SchemaIr::Never => "Never".to_string(),

        SchemaIr::Literal(lit) => match lit {
            LiteralValue::String(_) => "String".to_string(),
            LiteralValue::Number(_) => "Double".to_string(),
            LiteralValue::Integer(_) => "Int".to_string(),
            LiteralValue::Bool(_) => "Bool".to_string(),
            LiteralValue::Null => "Never?".to_string(),
        },

        SchemaIr::ConstEqual(_) | SchemaIr::ComplexEnum(_) => "AnyCodable".to_string(),

        SchemaIr::Enum(_) => {
            // For inline enums referenced as a type, use String
            // (named enums get their own type via emit_struct)
            "String".to_string()
        }

        SchemaIr::MixedEnum(_) => "AnyCodable".to_string(),

        SchemaIr::Array(arr) => {
            format!("[{}]", swift_type(&arr.items, defs))
        }

        SchemaIr::Tuple(_) => "[AnyCodable]".to_string(),

        SchemaIr::Object(_) => "[String: AnyCodable]".to_string(),

        SchemaIr::Record(rec) => {
            format!("[String: {}]", swift_type(&rec.value, defs))
        }

        SchemaIr::Union(members) | SchemaIr::ExclusiveUnion(members) => {
            if members.len() == 2 {
                let non_null: Vec<_> = members
                    .iter()
                    .filter(|m| !matches!(m, SchemaIr::Null))
                    .collect();
                if non_null.len() == 1 {
                    return format!("{}?", swift_type(non_null[0], defs));
                }
            }
            "AnyCodable".to_string()
        }

        SchemaIr::Intersection(_) => "AnyCodable".to_string(),

        SchemaIr::Nullable(inner) => format!("{}?", swift_type(inner, defs)),
        SchemaIr::Optional(inner) => format!("{}?", swift_type(inner, defs)),
        SchemaIr::Default(inner, _) => swift_type(inner, defs),
        SchemaIr::Describe(inner, _) => swift_type(inner, defs),
        SchemaIr::Not { base, .. } => swift_type(base, defs),
        SchemaIr::Conditional { base, .. } => swift_type(base, defs),
        SchemaIr::TypeGuarded(_) => "AnyCodable".to_string(),

        SchemaIr::Ref(name) | SchemaIr::Lazy(name) => {
            // A ref to a def that was never converted would not compile —
            // degrade to accept-all rather than emitting a dangling type name.
            if defs.iter().any(|d| d.name == *name) {
                sanitize_swift_name(name)
            } else {
                "AnyCodable".to_string()
            }
        }
    }
}

/// Convert a string to lowerCamelCase (Swift convention for properties).
/// Preserves already-camelCase input like "tradeId".
fn to_camel_case(s: &str) -> String {
    // If input has no separators and starts lowercase, it's already camelCase
    if !s.contains(|c: char| !c.is_ascii_alphanumeric())
        && s.chars().next().is_some_and(|c| c.is_ascii_lowercase())
    {
        let result = s.to_string();
        return if is_swift_keyword(&result) {
            format!("`{result}`")
        } else {
            result
        };
    }

    let parts: Vec<&str> = s
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
        .collect();

    if parts.is_empty() {
        return s.to_string();
    }

    let mut result = parts[0].to_lowercase();
    for part in &parts[1..] {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            result.push(first.to_ascii_uppercase());
            result.extend(chars);
        }
    }

    if is_swift_keyword(&result) {
        format!("`{result}`")
    } else {
        result
    }
}

// ── Field constraint extraction ──────────────────────────────────────────────

enum FieldGuard {
    // Numeric
    Minimum(f64),
    Maximum(f64),
    ExclusiveMinimum(f64),
    ExclusiveMaximum(f64),
    MultipleOf(f64),
    // String
    MinLength(u64),
    MaxLength(u64),
    Pattern(String),
    // Array
    MinItems(u64),
    MaxItems(u64),
}

/// Extract validation guards from a schema IR node.
fn field_guards(ir: &SchemaIr) -> Vec<FieldGuard> {
    match ir {
        SchemaIr::Number(c) | SchemaIr::Integer(c) => {
            let mut guards = Vec::new();
            if let Some(v) = c.minimum { guards.push(FieldGuard::Minimum(v)); }
            if let Some(v) = c.maximum { guards.push(FieldGuard::Maximum(v)); }
            if let Some(v) = c.exclusive_minimum { guards.push(FieldGuard::ExclusiveMinimum(v)); }
            if let Some(v) = c.exclusive_maximum { guards.push(FieldGuard::ExclusiveMaximum(v)); }
            if let Some(v) = c.multiple_of { guards.push(FieldGuard::MultipleOf(v)); }
            guards
        }
        SchemaIr::String(c) => {
            // Skip string constraints if a format type handles validation already
            if c.format.is_some() {
                return Vec::new();
            }
            let mut guards = Vec::new();
            if let Some(v) = c.min_length { guards.push(FieldGuard::MinLength(v)); }
            if let Some(v) = c.max_length { guards.push(FieldGuard::MaxLength(v)); }
            if let Some(ref v) = c.pattern { guards.push(FieldGuard::Pattern(v.clone())); }
            guards
        }
        SchemaIr::Enum(_) => {
            // Handled via nested enum type, not a guard
            Vec::new()
        }
        SchemaIr::Array(arr) => {
            let mut guards = Vec::new();
            if let Some(v) = arr.min_items { guards.push(FieldGuard::MinItems(v)); }
            if let Some(v) = arr.max_items { guards.push(FieldGuard::MaxItems(v)); }
            guards
        }
        SchemaIr::Describe(inner, _) | SchemaIr::Default(inner, _) => field_guards(inner),
        _ => Vec::new(),
    }
}

/// Format a number for Swift source code — use integer form when possible.
fn format_number(n: f64) -> String {
    if n == n.trunc() && n.abs() < 1e15 {
        format!("{}", n as i64)
    } else {
        format!("{n}")
    }
}

/// Emit propertyNames validation for the Object struct path.
/// `keys_expr` is the Swift expression for the keys collection (e.g., "allKeysContainer.allKeys").
fn emit_property_names_check(
    pn: &SchemaIr,
    keys_expr: &str,
    lines: &mut Vec<String>,
    preamble: &mut String,
    defs: &[DefEntry],
) {
    let inner = unwrap_modifiers(pn);
    match inner {
        SchemaIr::Never => {
            lines.push(format!("        if !{keys_expr}.isEmpty {{ throw ValidationError.outOfRange(\"value\", \"propertyNames: no properties allowed\") }}"));
        }
        SchemaIr::String(c) => {
            lines.push(format!("        for key in {keys_expr} {{"));
            if let Some(max) = c.max_length {
                lines.push(format!("            if key.stringValue.count > {max} {{ throw ValidationError.outOfRange(key.stringValue, \"propertyNames\") }}"));
            }
            if let Some(min) = c.min_length {
                lines.push(format!("            if key.stringValue.count < {min} {{ throw ValidationError.outOfRange(key.stringValue, \"propertyNames\") }}"));
            }
            if let Some(ref pat) = c.pattern {
                lines.push(format!("            if key.stringValue.range(of: \"{}\", options: .regularExpression) == nil {{ throw ValidationError.outOfRange(key.stringValue, \"propertyNames\") }}", swift_escape(pat)));
            }
            lines.push("        }".to_string());
        }
        SchemaIr::Literal(LiteralValue::String(s)) => {
            let escaped = swift_escape(s);
            lines.push(format!("        for key in {keys_expr} {{ if key.stringValue != \"{escaped}\" {{ throw ValidationError.outOfRange(key.stringValue, \"propertyNames\") }} }}"));
        }
        SchemaIr::Enum(cases) => {
            let allowed: Vec<String> = cases.iter().map(|c| format!("\"{}\"", swift_escape(c))).collect();
            lines.push(format!("        let _pnAllowed: Set<String> = [{}]", allowed.join(", ")));
            lines.push(format!("        for key in {keys_expr} {{ if !_pnAllowed.contains(key.stringValue) {{ throw ValidationError.outOfRange(key.stringValue, \"propertyNames\") }} }}"));
        }
        _ => {
            // Generic: serialize each key as JSON string and validate against sub-schema
            let mut sub_counter = 0usize;
            let (sub_pre, pn_type) = emit_swift_sub_schema("PN", pn, defs, &mut sub_counter);
            if !sub_pre.is_empty() {
                preamble.push_str(&sub_pre);
            }
            if pn_type != "AnyCodable" {
                lines.push(format!("        for key in {keys_expr} {{ let kd = _serializeAny(key.stringValue); let _ = try JSONDecoder().decode({pn_type}.self, from: kd) }}"));
            }
        }
    }
}

/// Emit propertyNames validation for the TypeGuarded wrapper path.
/// Uses `dict.keys` iteration (different syntax from the keyed container approach).
fn emit_property_names_check_tg(
    pn: &SchemaIr,
    checks: &mut Vec<String>,
    preamble: &mut String,
    defs: &[DefEntry],
) {
    let inner = unwrap_modifiers(pn);
    match inner {
        SchemaIr::Never => {
            checks.push("            if !dict.isEmpty { throw ValidationError.outOfRange(\"value\", \"propertyNames: no properties allowed\") }".to_string());
        }
        SchemaIr::String(c) => {
            if let Some(max) = c.max_length {
                checks.push(format!("            for k in dict.keys {{ if k.count > {max} {{ throw ValidationError.outOfRange(k, \"propertyNames\") }} }}"));
            }
            if let Some(min) = c.min_length {
                checks.push(format!("            for k in dict.keys {{ if k.count < {min} {{ throw ValidationError.outOfRange(k, \"propertyNames\") }} }}"));
            }
            if let Some(ref pat) = c.pattern {
                checks.push(format!("            for k in dict.keys {{ if k.range(of: \"{}\", options: .regularExpression) == nil {{ throw ValidationError.outOfRange(k, \"propertyNames\") }} }}", swift_escape(pat)));
            }
        }
        SchemaIr::Literal(LiteralValue::String(s)) => {
            let escaped = swift_escape(s);
            checks.push(format!("            for k in dict.keys {{ if k != \"{escaped}\" {{ throw ValidationError.outOfRange(k, \"propertyNames\") }} }}"));
        }
        SchemaIr::Enum(cases) => {
            let allowed: Vec<String> = cases.iter().map(|c| format!("\"{}\"", swift_escape(c))).collect();
            checks.push(format!("            let _pnAllowed: Set<String> = [{}]", allowed.join(", ")));
            checks.push("            for k in dict.keys { if !_pnAllowed.contains(k) { throw ValidationError.outOfRange(k, \"propertyNames\") } }".to_string());
        }
        _ => {
            // Generic: serialize each key as JSON string and validate against sub-schema
            let mut sub_counter = 0usize;
            let (sub_pre, pn_type) = emit_swift_sub_schema("PN", pn, defs, &mut sub_counter);
            if !sub_pre.is_empty() {
                preamble.push_str(&sub_pre);
            }
            if pn_type != "AnyCodable" {
                checks.push(format!("            for k in dict.keys {{ let kd = _serializeAny(k); let _ = try JSONDecoder().decode({pn_type}.self, from: kd) }}"));
            }
        }
    }
}

/// Emit Swift guard statements for a single field's constraints.
fn emit_guard_lines(
    swift_name: &str,
    optional: bool,
    guards: &[FieldGuard],
    lines: &mut Vec<String>,
) {
    for guard in guards {
        let v = if optional { "v" } else { swift_name };

        match guard {
            FieldGuard::Minimum(n) => {
                let bound = format_number(*n);
                emit_comparison(swift_name, v, optional, ">=", &bound, &format!(">= {bound}"), lines);
            }
            FieldGuard::Maximum(n) => {
                let bound = format_number(*n);
                emit_comparison(swift_name, v, optional, "<=", &bound, &format!("<= {bound}"), lines);
            }
            FieldGuard::ExclusiveMinimum(n) => {
                let bound = format_number(*n);
                emit_comparison(swift_name, v, optional, ">", &bound, &format!("> {bound}"), lines);
            }
            FieldGuard::ExclusiveMaximum(n) => {
                let bound = format_number(*n);
                emit_comparison(swift_name, v, optional, "<", &bound, &format!("< {bound}"), lines);
            }
            FieldGuard::MultipleOf(n) => {
                let bound = format_number(*n);
                let msg = format!("must be a multiple of {bound}");
                if optional {
                    lines.push(format!(
                        "        if let v = {swift_name} {{ if (Double(v) / {bound}).isInfinite {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}; let _mof = Double(v).remainder(dividingBy: {bound}); if _mof.isNaN || _mof.isInfinite || (abs(_mof) > 1e-9 && abs(abs(_mof) - {bound}) > 1e-9) {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }} }}"
                    ));
                } else {
                    lines.push(format!(
                        "        if (Double({v}) / {bound}).isInfinite {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
                    ));
                    lines.push(format!(
                        "        let _mof = Double({v}).remainder(dividingBy: {bound})"
                    ));
                    lines.push(format!(
                        "        if _mof.isNaN || _mof.isInfinite || (abs(_mof) > 1e-9 && abs(abs(_mof) - {bound}) > 1e-9) {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
                    ));
                }
            }
            FieldGuard::MinLength(n) => {
                let msg = format!("length must be >= {n}");
                if optional {
                    lines.push(format!(
                        "        if let v = {swift_name}, v.count < {n} {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
                    ));
                } else {
                    lines.push(format!(
                        "        if {v}.count < {n} {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
                    ));
                }
            }
            FieldGuard::MaxLength(n) => {
                let msg = format!("length must be <= {n}");
                if optional {
                    lines.push(format!(
                        "        if let v = {swift_name}, v.count > {n} {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
                    ));
                } else {
                    lines.push(format!(
                        "        if {v}.count > {n} {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
                    ));
                }
            }
            FieldGuard::Pattern(pat) => {
                let escaped = swift_escape(pat);
                let msg = format!("must match pattern {escaped}");
                if optional {
                    lines.push(format!(
                        "        if let v = {swift_name}, v.range(of: \"{escaped}\", options: .regularExpression) == nil {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
                    ));
                } else {
                    lines.push(format!(
                        "        if {v}.range(of: \"{escaped}\", options: .regularExpression) == nil {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
                    ));
                }
            }
            FieldGuard::MinItems(n) => {
                let msg = format!("must have at least {n} items");
                if optional {
                    lines.push(format!(
                        "        if let v = {swift_name}, v.count < {n} {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
                    ));
                } else {
                    lines.push(format!(
                        "        if {v}.count < {n} {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
                    ));
                }
            }
            FieldGuard::MaxItems(n) => {
                let msg = format!("must have at most {n} items");
                if optional {
                    lines.push(format!(
                        "        if let v = {swift_name}, v.count > {n} {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
                    ));
                } else {
                    lines.push(format!(
                        "        if {v}.count > {n} {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
                    ));
                }
            }
        }
    }
}

fn emit_comparison(
    swift_name: &str,
    v: &str,
    optional: bool,
    op: &str,
    bound: &str,
    msg: &str,
    lines: &mut Vec<String>,
) {
    if optional {
        lines.push(format!(
            "        if let v = {swift_name}, !(v {op} {bound}) {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
        ));
    } else {
        lines.push(format!(
            "        if !({v} {op} {bound}) {{ throw ValidationError.outOfRange(\"{swift_name}\", \"{msg}\") }}"
        ));
    }
}

fn is_swift_keyword(s: &str) -> bool {
    matches!(
        s,
        "as" | "break" | "case" | "catch" | "class" | "continue" | "default" | "defer"
            | "do" | "else" | "enum" | "extension" | "fallthrough" | "false" | "for"
            | "func" | "guard" | "if" | "import" | "in" | "init" | "inout" | "internal"
            | "is" | "let" | "nil" | "operator" | "private" | "protocol" | "public"
            | "repeat" | "return" | "self" | "static" | "struct" | "subscript" | "super"
            | "switch" | "throw" | "throws" | "true" | "try" | "typealias" | "var"
            | "where" | "while" | "type" | "description"
    )
}
