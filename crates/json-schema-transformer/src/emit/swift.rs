fn emit_conditional_wrapper(
    name: &str,
    if_schema: &SchemaIr,
    then_schema: Option<&SchemaIr>,
    else_schema: Option<&SchemaIr>,
    defs: &[DefEntry],
) -> String {
    let mut counter = 0usize;
    let mut preamble = String::new();
    let (p, if_type) = emit_swift_sub_schema("If", if_schema, defs, &mut counter);
    preamble.push_str(&p);
    let mut body = Vec::new();
    body.push("        let data = _serializeAny(raw.value)".to_string());
    body.push(format!(
        "        let ifMatched = (try? JSONDecoder().decode({if_type}.self, from: data)) != nil"
    ));
    if let Some(then_s) = then_schema {
        let (p, then_type) = emit_swift_sub_schema("Then", then_s, defs, &mut counter);
        preamble.push_str(&p);
        body.push(format!(
            "        if ifMatched {{ let _ = try JSONDecoder().decode({then_type}.self, from: data) }}"
        ));
    }
    if let Some(else_s) = else_schema {
        let (p, else_type) = emit_swift_sub_schema("Else", else_s, defs, &mut counter);
        preamble.push_str(&p);
        body.push(format!(
            "        if !ifMatched {{ let _ = try JSONDecoder().decode({else_type}.self, from: data) }}"
        ));
    }

    let struct_body = format!(
        "struct {name}: Codable {{\n    let value: AnyCodable\n\n    // @validate\n    init(from decoder: Decoder) throws {{\n        let container = try decoder.singleValueContainer()\n        let raw = try container.decode(AnyCodable.self)\n        value = raw\n{}\n    }}\n\n    func encode(to encoder: Encoder) throws {{\n        var container = encoder.singleValueContainer()\n        try container.encode(value)\n    }}\n}}",
        body.join("\n")
    );
    format!("{preamble}{struct_body}")
}

