// ── Swift string escaping ────────────────────────────────────────────────────

/// Escape a string for use in a Swift string literal.
/// Handles all control characters using Swift's \u{XX} syntax.
fn swift_escape(s: &str) -> String {
    s.chars()
        .flat_map(|c| match c {
            '"' => vec!['\\', '"'],
            '\\' => vec!['\\', '\\'],
            '\n' => vec!['\\', 'n'],
            '\r' => vec!['\\', 'r'],
            '\t' => vec!['\\', 't'],
            '\0' => vec!['\\', '0'],
            c if c.is_control() => {
                format!("\\u{{{:02X}}}", c as u32).chars().collect()
            }
            other => vec![other],
        })
        .collect()
}

// ── Name sanitization ───────────────────────────────────────────────────────

/// Swift reserved type names that must not be used as generated type names.
const SWIFT_RESERVED_TYPES: &[&str] = &[
    "Bool", "Int", "Int8", "Int16", "Int32", "Int64",
    "UInt", "UInt8", "UInt16", "UInt32", "UInt64",
    "Float", "Double", "String", "Character",
    "Array", "Dictionary", "Set", "Optional",
    "Never", "Void", "Any", "AnyObject", "AnyHashable",
    "Error", "Result", "Data", "Date", "URL", "UUID",
    "Codable", "Decodable", "Encodable",
    "Equatable", "Hashable", "Comparable",
    "Type",
];

fn sanitize_swift_name(name: &str) -> String {
    let base = if SWIFT_RESERVED_TYPES.contains(&name) {
        format!("{name}Schema")
    } else {
        name.to_string()
    };
    // Prefix with the per-file root type prefix so $defs types with generic
    // names (Address, Node, …) never collide across files in one module.
    TYPE_PREFIX.with(|p| format!("{}{}", p.borrow(), base))
}

/// Mark a top-level generated declaration `private` (Swift top-level `private`
/// is file-scoped, so every generated file may safely re-declare the same
/// helper names when compiled into a single module).
fn privatize_decl(code: String, name: &str) -> String {
    code.replacen(&format!("struct {name}:"), &format!("private struct {name}:"), 1)
        .replacen(&format!("enum {name}:"), &format!("private enum {name}:"), 1)
        .replacen(&format!("final class {name}:"), &format!("private final class {name}:"), 1)
        .replacen(&format!("typealias {name} ="), &format!("private typealias {name} ="), 1)
}

// ── Struct emission ──────────────────────────────────────────────────────────

fn emit_struct(name: &str, ir: &SchemaIr, defs: &[DefEntry]) -> String {
    match ir {
        SchemaIr::Object(obj) => {
            let mut preamble = String::new();
            let mut lines = vec![format!("struct {name}: Codable {{")];

            let mut needs_coding_keys = false;
            let mut fields_info: Vec<(&str, String, String, bool, Vec<FieldGuard>)> = Vec::new();
            let mut has_field_constraints = false;
            let forbid_extra = matches!(obj.additional_properties, AdditionalProperties::Forbidden);
            let has_pattern_props = !obj.pattern_properties.is_empty();
            let has_property_names = obj.property_names.is_some();
            let has_min_props = obj.min_properties.is_some();
            let has_max_props = obj.max_properties.is_some();
            let has_dep_required = !obj.dependent_required.is_empty();
            let has_dep_schemas = !obj.dependent_schemas.is_empty();
            let has_ap_schema = matches!(obj.additional_properties, AdditionalProperties::Schema(_));
            let mut nested_enums: Vec<String> = Vec::new();
            let mut seen_names: std::collections::HashMap<String, usize> = std::collections::HashMap::new();

            for (k, f) in &obj.fields {
                let mut swift_name = to_camel_case(k);
                let count = seen_names.entry(swift_name.clone()).or_insert(0);
                *count += 1;
                if *count > 1 {
                    swift_name = format!("{swift_name}{count}");
                }
                let optional = !f.required;
                let guards = field_guards(&f.schema);

                // Generate nested enum for inline string enums
                let field_type = if let SchemaIr::Enum(cases) = &f.schema {
                    let enum_name = to_pascal_case(k);
                    nested_enums.push(emit_nested_enum(&enum_name, cases));
                    enum_name
                } else {
                    swift_type(&f.schema, defs)
                };

                if swift_name != *k {
                    needs_coding_keys = true;
                }
                if !guards.is_empty() {
                    has_field_constraints = true;
                }

                let type_str = if optional {
                    format!("{field_type}?")
                } else {
                    field_type.clone()
                };

                lines.push(format!("    let {swift_name}: {type_str}"));
                fields_info.push((k, swift_name, field_type, optional, guards));
            }

            // Emit nested enums
            if !nested_enums.is_empty() {
                lines.push(String::new());
                for e in &nested_enums {
                    lines.push(e.clone());
                }
            }

            let needs_custom_init = has_field_constraints || forbid_extra
                || has_pattern_props || has_property_names
                || has_min_props || has_max_props
                || has_dep_required || has_dep_schemas || has_ap_schema;
            // CodingKeys needed when names differ OR when we need a custom init(from:)
            let needs_coding_keys = needs_coding_keys || needs_custom_init;

            if needs_coding_keys && !fields_info.is_empty() {
                lines.push(String::new());
                lines.push("    enum CodingKeys: String, CodingKey {".to_string());
                for (json_key, swift_name, _, _, _) in &fields_info {
                    if *swift_name != *json_key {
                        lines.push(format!(
                            "        case {swift_name} = \"{}\"",
                            swift_escape(json_key)
                        ));
                    } else {
                        lines.push(format!("        case {swift_name}"));
                    }
                }
                lines.push("    }".to_string());
            }

            // Custom init(from:) for field validation and/or additionalProperties check
            if needs_custom_init {
                // Leave a comment so the helper detector knows we need ValidationError
                lines.push(String::new());
                lines.push("    // @validate".to_string());
                lines.push("    init(from decoder: Decoder) throws {".to_string());
                if !fields_info.is_empty() {
                    lines.push("        let container = try decoder.container(keyedBy: CodingKeys.self)".to_string());
                }

                // DynamicKey needed for key iteration (forbid_extra, patternProperties, AP schema, propertyNames, min/maxProperties, dependentRequired/Schemas)
                let needs_dynamic_keys = forbid_extra || has_pattern_props || has_ap_schema
                    || has_property_names || has_min_props || has_max_props
                    || has_dep_required || has_dep_schemas;
                if needs_dynamic_keys {
                    lines.push("        struct DynamicKey: CodingKey { var stringValue: String; init?(stringValue: String) { self.stringValue = stringValue }; var intValue: Int?; init?(intValue: Int) { return nil } }".to_string());
                    lines.push("        let allKeysContainer = try decoder.container(keyedBy: DynamicKey.self)".to_string());
                    let known_json_keys: Vec<String> = fields_info.iter().map(|(jk, _, _, _, _)| format!("\"{}\"", swift_escape(jk))).collect();
                    lines.push(format!(
                        "        let knownKeys: Set<String> = [{}]",
                        known_json_keys.join(", ")
                    ));
                }

                // forbid_extra: reject unexpected keys
                if forbid_extra && !has_pattern_props {
                    lines.push(
                        "        for key in allKeysContainer.allKeys where !knownKeys.contains(key.stringValue) { throw ValidationError.outOfRange(key.stringValue, \"unexpected property\") }".to_string()
                    );
                }

                // Decode fields
                for (_, swift_name, swift_type, optional, guards) in &fields_info {
                    if *optional {
                        lines.push(format!(
                            "        {swift_name} = try container.decodeIfPresent({swift_type}.self, forKey: .{swift_name})"
                        ));
                    } else {
                        lines.push(format!(
                            "        {swift_name} = try container.decode({swift_type}.self, forKey: .{swift_name})"
                        ));
                    }
                    emit_guard_lines(swift_name, *optional, guards, &mut lines);
                }

                // minProperties / maxProperties
                if has_min_props || has_max_props {
                    lines.push("        let propCount = allKeysContainer.allKeys.count".to_string());
                    if let Some(min) = obj.min_properties {
                        lines.push(format!("        if propCount < {min} {{ throw ValidationError.outOfRange(\"value\", \"minProperties\") }}"));
                    }
                    if let Some(max) = obj.max_properties {
                        lines.push(format!("        if propCount > {max} {{ throw ValidationError.outOfRange(\"value\", \"maxProperties\") }}"));
                    }
                }

                // patternProperties + additionalProperties interaction
                if has_pattern_props {
                    lines.push("        for key in allKeysContainer.allKeys {".to_string());
                    lines.push("            var matched = knownKeys.contains(key.stringValue)".to_string());
                    for (pattern, pp_schema) in &obj.pattern_properties {
                        let mut pp_c = 0usize;
                        let (pp_pre, pt) = emit_swift_sub_schema("PP", pp_schema, defs, &mut pp_c);
                        if !pp_pre.is_empty() { preamble.push_str(&pp_pre); }
                        lines.push(format!(
                            "            if key.stringValue.range(of: \"{}\", options: .regularExpression) != nil {{ matched = true; let pv = try allKeysContainer.decode(AnyCodable.self, forKey: key); let pd = _serializeAny(pv.value); let _ = try JSONDecoder().decode({pt}.self, from: pd) }}",
                            swift_escape(pattern)
                        ));
                    }
                    if forbid_extra {
                        lines.push("            if !matched { throw ValidationError.outOfRange(key.stringValue, \"unexpected property\") }".to_string());
                    }
                    lines.push("        }".to_string());
                } else if has_ap_schema {
                    // additionalProperties with schema validation
                    if let AdditionalProperties::Schema(ap) = &obj.additional_properties {
                        let mut ap_c = 0usize;
                        let (ap_pre, at) = emit_swift_sub_schema("AP", ap, defs, &mut ap_c);
                        if !ap_pre.is_empty() { preamble.push_str(&ap_pre); }
                        lines.push("        for key in allKeysContainer.allKeys where !knownKeys.contains(key.stringValue) {".to_string());
                        lines.push(format!("            let av = try allKeysContainer.decode(AnyCodable.self, forKey: key); let ad = _serializeAny(av.value); let _ = try JSONDecoder().decode({at}.self, from: ad)"));
                        lines.push("        }".to_string());
                    }
                }

                // propertyNames
                if let Some(pn) = &obj.property_names {
                    emit_property_names_check(pn, "allKeysContainer.allKeys", &mut lines, &mut preamble, defs);
                }

                // dependentRequired
                for (prop, required) in &obj.dependent_required {
                    let trigger_key = swift_escape(prop);
                    lines.push(format!("        if allKeysContainer.allKeys.contains(where: {{ $0.stringValue == \"{}\" }}) {{", trigger_key));
                    for r in required {
                        let rk = swift_escape(r);
                        lines.push(format!("            if !allKeysContainer.allKeys.contains(where: {{ $0.stringValue == \"{rk}\" }}) {{ throw ValidationError.outOfRange(\"{rk}\", \"dependentRequired\") }}"));
                    }
                    lines.push("        }".to_string());
                }

                // dependentSchemas — decode raw dict once, then validate
                if has_dep_schemas {
                    lines.push("        var rawDict: [String: AnyCodable] = [:]".to_string());
                    lines.push("        for key in allKeysContainer.allKeys { rawDict[key.stringValue] = try allKeysContainer.decode(AnyCodable.self, forKey: key) }".to_string());
                    lines.push("        let rawData = _serializeAny(rawDict.mapValues { $0.value })".to_string());
                    let mut ds_counter = 0usize;
                    for (prop, dep_schema) in &obj.dependent_schemas {
                        let (sub_pre, dt) = emit_swift_sub_schema("DS", dep_schema, defs, &mut ds_counter);
                        if !sub_pre.is_empty() {
                            preamble.push_str(&sub_pre);
                        }
                        let trigger_key = swift_escape(prop);
                        lines.push(format!("        if rawDict[\"{trigger_key}\"] != nil {{"));
                        lines.push(format!("            let _ = try JSONDecoder().decode({dt}.self, from: rawData)"));
                        lines.push("        }".to_string());
                    }
                }

                lines.push("    }".to_string());
            }

            lines.push("}".to_string());
            format!("{preamble}{}", lines.join("\n"))
        }

        SchemaIr::Enum(cases) if cases.is_empty() => {
            // Empty enum — reject all values
            format!(
                "struct {name}: Codable {{\n    // @validate\n    init(from decoder: Decoder) throws {{\n        throw ValidationError.outOfRange(\"value\", \"schema rejects all values\")\n    }}\n    func encode(to encoder: Encoder) throws {{}}\n}}"
            )
        }

        SchemaIr::Enum(cases) => {
            let mut lines = vec![format!("enum {name}: String, Codable {{")];
            let mut seen_cases: std::collections::HashMap<String, usize> = std::collections::HashMap::new();
            for case in cases {
                let mut swift_case = to_camel_case(case);
                let count = seen_cases.entry(swift_case.clone()).or_insert(0);
                *count += 1;
                if *count > 1 {
                    swift_case = format!("{swift_case}{count}");
                }
                if swift_case != *case {
                    lines.push(format!(
                        "    case {swift_case} = \"{}\"",
                        swift_escape(case)
                    ));
                } else {
                    lines.push(format!("    case {swift_case}"));
                }
            }
            lines.push("}".to_string());
            lines.join("\n")
        }

        _ => {
            if should_emit_wrapper(ir) {
                emit_wrapper_struct(name, ir, defs)
            } else {
                format!("typealias {name} = {}", swift_type(ir, defs))
            }
        }
    }
}

/// Determine if a non-Object IR node needs a wrapper struct for validation.
fn should_emit_wrapper(ir: &SchemaIr) -> bool {
    match ir {
        SchemaIr::Integer(_) | SchemaIr::Number(_) | SchemaIr::Boolean => true,
        SchemaIr::String(c) => {
            c.min_length.is_some() || c.max_length.is_some() || c.pattern.is_some()
        }
        SchemaIr::Array(arr) => {
            arr.min_items.is_some()
                || arr.max_items.is_some()
                || arr.unique_items
                || arr.contains.is_some()
                || !matches!(arr.items.as_ref(), SchemaIr::Any)
        }
        SchemaIr::MixedEnum(_) | SchemaIr::Literal(_) | SchemaIr::ConstEqual(_)
        | SchemaIr::ComplexEnum(_) | SchemaIr::TypeGuarded(_) | SchemaIr::Never
        | SchemaIr::Null => true,
        SchemaIr::Not { .. } | SchemaIr::Conditional { .. } | SchemaIr::ExclusiveUnion(_) => true,
        SchemaIr::Union(members) if members.len() > 1 => true,
        SchemaIr::Enum(cases) if cases.is_empty() => true,
        SchemaIr::Intersection(members) if members.len() > 1 => true,
        SchemaIr::Intersection(members) if members.len() == 1 => should_emit_wrapper(&members[0]),
        SchemaIr::Nullable(inner) | SchemaIr::Describe(inner, _) | SchemaIr::Default(inner, _) => {
            should_emit_wrapper(inner)
        }
        _ => false,
    }
}

/// Emit a wrapper struct with single-value decoding and validation.
fn emit_wrapper_struct(name: &str, ir: &SchemaIr, defs: &[DefEntry]) -> String {
    // Track if outer IR was Nullable before unwrapping
    let is_nullable = matches!(ir, SchemaIr::Nullable(_));
    // Unwrap modifiers
    let inner = unwrap_modifiers(ir);

    match inner {
        SchemaIr::Integer(c) => emit_numeric_wrapper(name, "Int", c, true),
        SchemaIr::Number(c) => emit_numeric_wrapper(name, "Double", c, false),
        SchemaIr::Boolean => {
            format!(
                "struct {name}: Codable {{\n    let value: Bool\n\n    // @validate\n    init(from decoder: Decoder) throws {{\n        let container = try decoder.singleValueContainer()\n        let raw = try container.decode(AnyCodable.self)\n        guard raw.value is Bool else {{\n            throw ValidationError.outOfRange(\"value\", \"expected boolean, got non-boolean\")\n        }}\n        value = raw.value as! Bool\n    }}\n\n    func encode(to encoder: Encoder) throws {{\n        var container = encoder.singleValueContainer()\n        try container.encode(value)\n    }}\n}}"
            )
        }
        SchemaIr::String(c) => emit_string_wrapper(name, c),
        SchemaIr::Array(arr) => emit_array_wrapper(name, arr, defs),
        SchemaIr::TypeGuarded(guards) => emit_type_guarded_wrapper(name, guards, defs),
        SchemaIr::MixedEnum(lits) => emit_mixed_enum_wrapper(name, lits),
        SchemaIr::Literal(lit) => emit_literal_wrapper(name, lit),
        SchemaIr::ConstEqual(val) => emit_const_equal_wrapper(name, val),
        SchemaIr::ComplexEnum(vals) => emit_complex_enum_wrapper(name, vals),
        SchemaIr::Null => {
            format!(
                "struct {name}: Codable {{\n    let value: AnyCodable\n\n    // @validate\n    init(from decoder: Decoder) throws {{\n        let container = try decoder.singleValueContainer()\n        let raw = try container.decode(AnyCodable.self)\n        guard raw.value is NSNull else {{ throw ValidationError.outOfRange(\"value\", \"expected null\") }}\n        value = raw\n    }}\n\n    func encode(to encoder: Encoder) throws {{\n        var container = encoder.singleValueContainer()\n        try container.encode(value)\n    }}\n}}"
            )
        }
        SchemaIr::Never => {
            format!(
                "struct {name}: Codable {{\n    // @validate\n    init(from decoder: Decoder) throws {{\n        throw ValidationError.outOfRange(\"value\", \"schema rejects all values\")\n    }}\n    func encode(to encoder: Encoder) throws {{}}\n}}"
            )
        }
        SchemaIr::Not { base, not_schema } => emit_not_wrapper(name, base, not_schema, defs),
        SchemaIr::Conditional { base: _, if_schema, then_schema, else_schema } => {
            emit_conditional_wrapper(name, if_schema, then_schema.as_deref(), else_schema.as_deref(), defs)
        }
        SchemaIr::Union(members) if members.len() > 1 => {
            if is_nullable {
                let mut extended = members.to_vec();
                extended.push(SchemaIr::Null);
                emit_anyof_wrapper(name, &extended, defs)
            } else {
                emit_anyof_wrapper(name, members, defs)
            }
        }
        SchemaIr::ExclusiveUnion(members) => emit_oneof_wrapper(name, members, defs),
        SchemaIr::Intersection(members) => emit_intersection_wrapper(name, members, defs),
        SchemaIr::Object(_) | SchemaIr::Tuple(_) => emit_struct(name, inner, defs),
        SchemaIr::Enum(cases) if cases.is_empty() => {
            format!(
                "struct {name}: Codable {{\n    // @validate\n    init(from decoder: Decoder) throws {{\n        throw ValidationError.outOfRange(\"value\", \"schema rejects all values\")\n    }}\n    func encode(to encoder: Encoder) throws {{}}\n}}"
            )
        }
        SchemaIr::Enum(_) => emit_struct(name, inner, defs),
        _ => format!("typealias {name} = {}", swift_type(ir, defs)),
    }
}

fn unwrap_modifiers(ir: &SchemaIr) -> &SchemaIr {
    match ir {
        SchemaIr::Describe(inner, _) | SchemaIr::Default(inner, _) | SchemaIr::Nullable(inner) => {
            unwrap_modifiers(inner)
        }
        _ => ir,
    }
}

fn emit_numeric_wrapper(name: &str, swift_ty: &str, c: &NumberConstraints, is_int: bool) -> String {
    let mut guards = Vec::new();
    if is_int {
        guards.push(format!(
            "        guard !(raw.value is Bool) else {{ throw ValidationError.outOfRange(\"value\", \"boolean is not {}\")}}", if is_int { "an integer" } else { "a number" }
        ));
        // Accept Int or Double (if whole number) for integer type
        guards.push(format!(
            "        if let i = raw.value as? Int {{ value = i }} else if let d = raw.value as? Double, d == d.rounded(.towardZero), d >= Double(Int.min), d <= Double(Int.max) {{ value = Int(d) }} else {{ throw ValidationError.outOfRange(\"value\", \"expected {swift_ty}\") }}"
        ));
    } else {
        guards.push(format!(
            "        guard !(raw.value is Bool) else {{ throw ValidationError.outOfRange(\"value\", \"boolean is not a number\")}}"
        ));
        guards.push(format!(
            "        if let d = raw.value as? Double {{ value = d }} else if let i = raw.value as? Int {{ value = Double(i) }} else {{ throw ValidationError.outOfRange(\"value\", \"expected {swift_ty}\") }}"
        ));
    }
    // Numeric constraint guards
    if let Some(v) = c.minimum {
        let b = format_number(v);
        guards.push(format!("        if !(value >= {b}) {{ throw ValidationError.outOfRange(\"value\", \">= {b}\") }}"));
    }
    if let Some(v) = c.maximum {
        let b = format_number(v);
        guards.push(format!("        if !(value <= {b}) {{ throw ValidationError.outOfRange(\"value\", \"<= {b}\") }}"));
    }
    if let Some(v) = c.exclusive_minimum {
        let b = format_number(v);
        guards.push(format!("        if !(value > {b}) {{ throw ValidationError.outOfRange(\"value\", \"> {b}\") }}"));
    }
    if let Some(v) = c.exclusive_maximum {
        let b = format_number(v);
        guards.push(format!("        if !(value < {b}) {{ throw ValidationError.outOfRange(\"value\", \"< {b}\") }}"));
    }
    if let Some(v) = c.multiple_of {
        let b = format_number(v);
        if is_int {
            guards.push(format!("        if (Double(value) / {b}).isInfinite {{ throw ValidationError.outOfRange(\"value\", \"must be a multiple of {b}\") }}"));
            guards.push(format!("        let _mof = Double(value).remainder(dividingBy: {b})"));
            guards.push(format!("        if _mof.isNaN || _mof.isInfinite || (abs(_mof) > 1e-9 && abs(abs(_mof) - {b}) > 1e-9) {{ throw ValidationError.outOfRange(\"value\", \"must be a multiple of {b}\") }}"));
        } else {
            guards.push(format!("        if (value / {b}).isInfinite {{ throw ValidationError.outOfRange(\"value\", \"must be a multiple of {b}\") }}"));
            guards.push(format!("        let _mof = value.remainder(dividingBy: {b})"));
            guards.push(format!("        if _mof.isNaN || _mof.isInfinite || (abs(_mof) > 1e-9 && abs(abs(_mof) - {b}) > 1e-9) {{ throw ValidationError.outOfRange(\"value\", \"must be a multiple of {b}\") }}"));
        }
    }

    format!(
        "struct {name}: Codable {{\n    let value: {swift_ty}\n\n    // @validate\n    init(from decoder: Decoder) throws {{\n        let container = try decoder.singleValueContainer()\n        let raw = try container.decode(AnyCodable.self)\n{}\n    }}\n\n    func encode(to encoder: Encoder) throws {{\n        var container = encoder.singleValueContainer()\n        try container.encode(value)\n    }}\n}}",
        guards.join("\n")
    )
}

fn emit_string_wrapper(name: &str, c: &StringConstraints) -> String {
    let mut guards = Vec::new();
    if let Some(min) = c.min_length {
        guards.push(format!("        if value.count < {min} {{ throw ValidationError.outOfRange(\"value\", \"length must be >= {min}\") }}"));
    }
    if let Some(max) = c.max_length {
        guards.push(format!("        if value.count > {max} {{ throw ValidationError.outOfRange(\"value\", \"length must be <= {max}\") }}"));
    }
    if let Some(ref pat) = c.pattern {
        let escaped = swift_escape(pat);
        guards.push(format!("        if value.range(of: \"{escaped}\", options: .regularExpression) == nil {{ throw ValidationError.outOfRange(\"value\", \"must match pattern\") }}"));
    }

    format!(
        "struct {name}: Codable {{\n    let value: String\n\n    // @validate\n    init(from decoder: Decoder) throws {{\n        let container = try decoder.singleValueContainer()\n        value = try container.decode(String.self)\n{}\n    }}\n\n    func encode(to encoder: Encoder) throws {{\n        var container = encoder.singleValueContainer()\n        try container.encode(value)\n    }}\n}}",
        guards.join("\n")
    )
}

fn emit_array_wrapper(name: &str, arr: &ArraySchema, defs: &[DefEntry]) -> String {
    let mut guards = Vec::new();
    let mut preamble = String::new();

    if let Some(min) = arr.min_items {
        guards.push(format!("        if value.count < {min} {{ throw ValidationError.outOfRange(\"value\", \"must have at least {min} items\") }}"));
    }
    if let Some(max) = arr.max_items {
        guards.push(format!("        if value.count > {max} {{ throw ValidationError.outOfRange(\"value\", \"must have at most {max} items\") }}"));
    }

    // Item type validation (if items is not Any)
    if !matches!(arr.items.as_ref(), SchemaIr::Any) {
        let mut item_counter = 0usize;
        let (item_pre, item_type) = emit_swift_sub_schema("Item", &arr.items, defs, &mut item_counter);
        if !item_pre.is_empty() { preamble.push_str(&item_pre); }
        guards.push(format!(
            "        for (i, item) in value.enumerated() {{ let data = _serializeAny(item.value); let _ = try JSONDecoder().decode({item_type}.self, from: data) }}"
        ));
    }

    // UniqueItems
    if arr.unique_items {
        guards.push(
            "        let serialized = try value.map { try String(data: _serializeAny($0.value), encoding: .utf8) ?? \"\" }\n        if Set(serialized).count != value.count { throw ValidationError.outOfRange(\"value\", \"items must be unique\") }"
                .to_string(),
        );
    }

    // Contains
    if let Some(contains) = &arr.contains {
        let mut con_counter = 0usize;
        let (con_pre, contains_type) = emit_swift_sub_schema("Con", &contains.schema, defs, &mut con_counter);
        if !con_pre.is_empty() { preamble.push_str(&con_pre); }
        let min = contains.min_contains.unwrap_or(1);
        guards.push(format!(
            "        let matchCount = value.filter {{ item in (try? JSONDecoder().decode({contains_type}.self, from: _serializeAny(item.value))) != nil }}.count"
        ));
        guards.push(format!(
            "        if matchCount < {min} {{ throw ValidationError.outOfRange(\"value\", \"must contain at least {min} matching items\") }}"
        ));
        if let Some(max) = contains.max_contains {
            guards.push(format!(
                "        if matchCount > {max} {{ throw ValidationError.outOfRange(\"value\", \"must contain at most {max} matching items\") }}"
            ));
        }
    }

    let body = format!(
        "struct {name}: Codable {{\n    let value: [AnyCodable]\n\n    // @validate\n    init(from decoder: Decoder) throws {{\n        let container = try decoder.singleValueContainer()\n        value = try container.decode([AnyCodable].self)\n{}\n    }}\n\n    func encode(to encoder: Encoder) throws {{\n        var container = encoder.singleValueContainer()\n        try container.encode(value)\n    }}\n}}",
        guards.join("\n")
    );
    format!("{preamble}{body}")
}

fn emit_type_guarded_wrapper(name: &str, guards: &[(TypeGuard, Box<SchemaIr>)], defs: &[DefEntry]) -> String {
    let mut checks = Vec::new();
    let mut preamble = String::new();

    for (guard, schema) in guards {
        match guard {
            TypeGuard::String => {
                if let SchemaIr::String(c) = schema.as_ref() {
                    checks.push("        if let s = raw.value as? String {".to_string());
                    if let Some(min) = c.min_length {
                        checks.push(format!("            if s.count < {min} {{ throw ValidationError.outOfRange(\"value\", \"minLength\") }}"));
                    }
                    if let Some(max) = c.max_length {
                        checks.push(format!("            if s.count > {max} {{ throw ValidationError.outOfRange(\"value\", \"maxLength\") }}"));
                    }
                    if let Some(ref pat) = c.pattern {
                        let escaped = swift_escape(pat);
                        checks.push(format!("            if s.range(of: \"{escaped}\", options: .regularExpression) == nil {{ throw ValidationError.outOfRange(\"value\", \"pattern\") }}"));
                    }
                    checks.push("        }".to_string());
                }
            }
            TypeGuard::Number => {
                let c = match schema.as_ref() {
                    SchemaIr::Number(c) | SchemaIr::Integer(c) => c,
                    _ => continue,
                };
                checks.push("        if let n = raw.value as? Double, !(raw.value is Bool) {".to_string());
                if let Some(v) = c.minimum {
                    let b = format_number(v);
                    checks.push(format!("            if n < {b} {{ throw ValidationError.outOfRange(\"value\", \"minimum\") }}"));
                }
                if let Some(v) = c.maximum {
                    let b = format_number(v);
                    checks.push(format!("            if n > {b} {{ throw ValidationError.outOfRange(\"value\", \"maximum\") }}"));
                }
                if let Some(v) = c.exclusive_minimum {
                    let b = format_number(v);
                    checks.push(format!("            if n <= {b} {{ throw ValidationError.outOfRange(\"value\", \"exclusiveMinimum\") }}"));
                }
                if let Some(v) = c.exclusive_maximum {
                    let b = format_number(v);
                    checks.push(format!("            if n >= {b} {{ throw ValidationError.outOfRange(\"value\", \"exclusiveMaximum\") }}"));
                }
                if let Some(v) = c.multiple_of {
                    let b = format_number(v);
                    checks.push(format!("            if (n / {b}).isInfinite {{ throw ValidationError.outOfRange(\"value\", \"multipleOf\") }}"));
                    checks.push(format!("            let _mof = n.remainder(dividingBy: {b})"));
                    checks.push(format!("            if _mof.isNaN || _mof.isInfinite || (abs(_mof) > 1e-9 && abs(abs(_mof) - {b}) > 1e-9) {{ throw ValidationError.outOfRange(\"value\", \"multipleOf\") }}"));
                }
                checks.push("        } else if let n = raw.value as? Int, !(raw.value is Bool) {".to_string());
                if let Some(v) = c.minimum {
                    let b = format_number(v);
                    checks.push(format!("            if Double(n) < {b} {{ throw ValidationError.outOfRange(\"value\", \"minimum\") }}"));
                }
                if let Some(v) = c.maximum {
                    let b = format_number(v);
                    checks.push(format!("            if Double(n) > {b} {{ throw ValidationError.outOfRange(\"value\", \"maximum\") }}"));
                }
                if let Some(v) = c.exclusive_minimum {
                    let b = format_number(v);
                    checks.push(format!("            if Double(n) <= {b} {{ throw ValidationError.outOfRange(\"value\", \"exclusiveMinimum\") }}"));
                }
                if let Some(v) = c.exclusive_maximum {
                    let b = format_number(v);
                    checks.push(format!("            if Double(n) >= {b} {{ throw ValidationError.outOfRange(\"value\", \"exclusiveMaximum\") }}"));
                }
                if let Some(v) = c.multiple_of {
                    let b = format_number(v);
                    checks.push(format!("            if (Double(n) / {b}).isInfinite {{ throw ValidationError.outOfRange(\"value\", \"multipleOf\") }}"));
                    checks.push(format!("            let _mofi = Double(n).remainder(dividingBy: {b})"));
                    checks.push(format!("            if _mofi.isNaN || _mofi.isInfinite || (abs(_mofi) > 1e-9 && abs(abs(_mofi) - {b}) > 1e-9) {{ throw ValidationError.outOfRange(\"value\", \"multipleOf\") }}"));
                }
                checks.push("        }".to_string());
            }
            TypeGuard::Object => {
                if let SchemaIr::Object(obj) = schema.as_ref() {
                    checks.push("        if let dict = raw.value as? [String: Any] {".to_string());
                    for (k, f) in &obj.fields {
                        if f.required {
                            checks.push(format!(
                                "            if dict[\"{}\"] == nil {{ throw ValidationError.outOfRange(\"value\", \"missing required: {}\") }}",
                                swift_escape(k), swift_escape(k)
                            ));
                        }
                    }
                    // Field type validation via JSON round-trip
                    for (k, f) in &obj.fields {
                        if matches!(&f.schema, SchemaIr::Any | SchemaIr::Unknown) { continue; }
                        let mut fc = 0usize;
                        let (fp, ft) = emit_swift_sub_schema("FV", &f.schema, defs, &mut fc);
                        if !fp.is_empty() { preamble.push_str(&fp); }
                        checks.push(format!(
                            "            if dict[\"{k}\"] != nil {{ let fd = _serializeAny(dict[\"{k}\"]!); let _ = try JSONDecoder().decode({ft}.self, from: fd) }}",
                            k = swift_escape(k)
                        ));
                    }
                    if let Some(min) = obj.min_properties {
                        checks.push(format!("            if dict.count < {min} {{ throw ValidationError.outOfRange(\"value\", \"minProperties\") }}"));
                    }
                    if let Some(max) = obj.max_properties {
                        checks.push(format!("            if dict.count > {max} {{ throw ValidationError.outOfRange(\"value\", \"maxProperties\") }}"));
                    }
                    // patternProperties + additionalProperties
                    if !obj.pattern_properties.is_empty() {
                        let known: Vec<String> = obj.fields.keys().map(|k| format!("\"{}\"", swift_escape(k))).collect();
                        checks.push("            for (k, v) in dict {".to_string());
                        checks.push("                var matched = false".to_string());
                        for (pattern, pp_schema) in &obj.pattern_properties {
                            let mut pp_c = 0usize;
                            let (pp_pre, pt) = emit_swift_sub_schema("PP", pp_schema, defs, &mut pp_c);
                            if !pp_pre.is_empty() { preamble.push_str(&pp_pre); }
                            checks.push(format!(
                                "                if k.range(of: \"{}\", options: .regularExpression) != nil {{ matched = true; let pd = _serializeAny(v); let _ = try JSONDecoder().decode({pt}.self, from: pd) }}",
                                swift_escape(pattern)
                            ));
                        }
                        if matches!(obj.additional_properties, AdditionalProperties::Forbidden) {
                            let ks = if known.is_empty() { "Set<String>()".to_string() } else { format!("Set([{}])", known.join(", ")) };
                            checks.push(format!("                if !matched && !{ks}.contains(k) {{ throw ValidationError.outOfRange(k, \"unexpected property\") }}"));
                        } else if let AdditionalProperties::Schema(ap) = &obj.additional_properties {
                            let mut ap_c = 0usize;
                            let (ap_pre, at) = emit_swift_sub_schema("AP", ap, defs, &mut ap_c);
                            if !ap_pre.is_empty() { preamble.push_str(&ap_pre); }
                            let ks = if known.is_empty() { "Set<String>()".to_string() } else { format!("Set([{}])", known.join(", ")) };
                            checks.push(format!("                if !matched && !{ks}.contains(k) {{ let ad = _serializeAny(v); let _ = try JSONDecoder().decode({at}.self, from: ad) }}"));
                        }
                        checks.push("            }".to_string());
                    } else if matches!(obj.additional_properties, AdditionalProperties::Forbidden) {
                        let known: Vec<String> = obj.fields.keys().map(|k| format!("\"{}\"", swift_escape(k))).collect();
                        let ks = if known.is_empty() { "Set<String>()".to_string() } else { format!("Set([{}])", known.join(", ")) };
                        checks.push(format!("            for k in dict.keys where !{ks}.contains(k) {{ throw ValidationError.outOfRange(k, \"unexpected property\") }}"));
                    } else if let AdditionalProperties::Schema(ap) = &obj.additional_properties {
                        let mut ap_c = 0usize;
                        let (ap_pre, at) = emit_swift_sub_schema("AP", ap, defs, &mut ap_c);
                        if !ap_pre.is_empty() { preamble.push_str(&ap_pre); }
                        let known: Vec<String> = obj.fields.keys().map(|k| format!("\"{}\"", swift_escape(k))).collect();
                        let ks = if known.is_empty() { "Set<String>()".to_string() } else { format!("Set([{}])", known.join(", ")) };
                        if at != "AnyCodable" {
                            checks.push(format!("            for (k, v) in dict where !{ks}.contains(k) {{ let ad = _serializeAny(v); let _ = try JSONDecoder().decode({at}.self, from: ad) }}"));
                        }
                    }
                    // propertyNames
                    if let Some(pn) = &obj.property_names {
                        emit_property_names_check_tg(pn, &mut checks, &mut preamble, defs);
                    }
                    // dependentRequired
                    for (prop, required) in &obj.dependent_required {
                        for r in required {
                            checks.push(format!(
                                "            if dict[\"{}\"] != nil && dict[\"{}\"] == nil {{ throw ValidationError.outOfRange(\"{}\", \"dependentRequired\") }}",
                                swift_escape(prop), swift_escape(r), swift_escape(r)
                            ));
                        }
                    }
                    // dependentSchemas
                    let mut ds_counter = 0usize;
                    for (prop, dep_schema) in &obj.dependent_schemas {
                        let (sub_pre, dt) = emit_swift_sub_schema("DS", dep_schema, defs, &mut ds_counter);
                        if !sub_pre.is_empty() {
                            preamble.push_str(&sub_pre);
                        }
                        checks.push(format!(
                            "            if dict[\"{}\"] != nil {{ let dd = _serializeAny(raw.value); let _ = try JSONDecoder().decode({dt}.self, from: dd) }}",
                            swift_escape(prop)
                        ));
                    }
                    checks.push("        }".to_string());
                }
                // Record in Object TypeGuard
                if let SchemaIr::Record(rec) = schema.as_ref() {
                    let vt = swift_type(&rec.value, defs);
                    if vt != "AnyCodable" {
                        checks.push("        if let dict = raw.value as? [String: Any] {".to_string());
                        checks.push(format!("            for (_, v) in dict {{ let rd = _serializeAny(v); let _ = try JSONDecoder().decode({vt}.self, from: rd) }}"));
                        checks.push("        }".to_string());
                    }
                }
            }
            TypeGuard::Array => {
                if let SchemaIr::Array(arr) = schema.as_ref() {
                    checks.push("        if let arr = raw.value as? [Any] {".to_string());
                    if let Some(min) = arr.min_items {
                        checks.push(format!("            if arr.count < {min} {{ throw ValidationError.outOfRange(\"value\", \"minItems\") }}"));
                    }
                    if let Some(max) = arr.max_items {
                        checks.push(format!("            if arr.count > {max} {{ throw ValidationError.outOfRange(\"value\", \"maxItems\") }}"));
                    }
                    if !matches!(arr.items.as_ref(), SchemaIr::Any) {
                        let mut item_counter = 0usize;
                        let (item_pre, it) = emit_swift_sub_schema("ArrItem", &arr.items, defs, &mut item_counter);
                        if !item_pre.is_empty() { preamble.push_str(&item_pre); }
                        checks.push(format!("            for item in arr {{ let id = _serializeAny(item); let _ = try JSONDecoder().decode({it}.self, from: id) }}"));
                    }
                    if arr.unique_items {
                        checks.push("            let ser = try arr.map { try String(data: _serializeAny($0), encoding: .utf8) ?? \"\" }".to_string());
                        checks.push("            if Set(ser).count != arr.count { throw ValidationError.outOfRange(\"value\", \"uniqueItems\") }".to_string());
                    }
                    if let Some(contains) = &arr.contains {
                        let mut ct_counter = 0usize;
                        let (ct_pre, ct) = emit_swift_sub_schema("Con", &contains.schema, defs, &mut ct_counter);
                        if !ct_pre.is_empty() { preamble.push_str(&ct_pre); }
                        let min = contains.min_contains.unwrap_or(1);
                        checks.push(format!("            let mc = arr.filter {{ i in (try? JSONDecoder().decode({ct}.self, from: _serializeAny(i))) != nil }}.count"));
                        checks.push(format!("            if mc < {min} {{ throw ValidationError.outOfRange(\"value\", \"must contain at least {min} matching items\") }}"));
                        if let Some(max) = contains.max_contains {
                            checks.push(format!("            if mc > {max} {{ throw ValidationError.outOfRange(\"value\", \"must contain at most {max} matching items\") }}"));
                        }
                    }
                    checks.push("        }".to_string());
                }
                // Tuple in Array TypeGuard
                if let SchemaIr::Tuple(tuple) = schema.as_ref() {
                    checks.push("        if let arr = raw.value as? [Any] {".to_string());
                    for (i, item) in tuple.items.iter().enumerate() {
                        if matches!(item, SchemaIr::Any) { continue; }
                        let mut ti_c = 0usize;
                        let (ti_pre, it) = emit_swift_sub_schema("TI", item, defs, &mut ti_c);
                        if !ti_pre.is_empty() { preamble.push_str(&ti_pre); }
                        checks.push(format!("            if arr.count > {i} {{ let td = _serializeAny(arr[{i}]); let _ = try JSONDecoder().decode({it}.self, from: td) }}"));
                    }
                    let pc = tuple.items.len();
                    if let Some(rest) = &tuple.rest {
                        if !matches!(rest.as_ref(), SchemaIr::Any) {
                            let mut rest_c = 0usize;
                            let (rest_pre, rt) = emit_swift_sub_schema("Rest", rest, defs, &mut rest_c);
                            if !rest_pre.is_empty() { preamble.push_str(&rest_pre); }
                            checks.push(format!("            for ri in {pc}..<arr.count {{ let rd = _serializeAny(arr[ri]); let _ = try JSONDecoder().decode({rt}.self, from: rd) }}"));
                        }
                    } else {
                        checks.push(format!("            if arr.count > {pc} {{ throw ValidationError.outOfRange(\"value\", \"too many items\") }}"));
                    }
                    if let Some(min) = tuple.min_items {
                        checks.push(format!("            if arr.count < {min} {{ throw ValidationError.outOfRange(\"value\", \"minItems\") }}"));
                    }
                    if let Some(max) = tuple.max_items {
                        checks.push(format!("            if arr.count > {max} {{ throw ValidationError.outOfRange(\"value\", \"maxItems\") }}"));
                    }
                    if tuple.unique_items {
                        checks.push("            let ser = try arr.map { try String(data: _serializeAny($0), encoding: .utf8) ?? \"\" }".to_string());
                        checks.push("            if Set(ser).count != arr.count { throw ValidationError.outOfRange(\"value\", \"uniqueItems\") }".to_string());
                    }
                    checks.push("        }".to_string());
                }
            }
        }
    }

    let body = format!(
        "struct {name}: Codable {{\n    let value: AnyCodable\n\n    // @validate\n    init(from decoder: Decoder) throws {{\n        let container = try decoder.singleValueContainer()\n        let raw = try container.decode(AnyCodable.self)\n        value = raw\n{}\n    }}\n\n    func encode(to encoder: Encoder) throws {{\n        var container = encoder.singleValueContainer()\n        try container.encode(value)\n    }}\n}}",
        checks.join("\n")
    );
    format!("{preamble}{body}")
}

fn emit_literal_wrapper(name: &str, lit: &LiteralValue) -> String {
    let check = match lit {
        LiteralValue::Bool(b) => {
            let val = if *b { "true" } else { "false" };
            format!("        guard (raw.value as? Bool) == {val} else {{ throw ValidationError.outOfRange(\"value\", \"must be {val}\") }}")
        }
        LiteralValue::Integer(i) => {
            format!("        guard !(raw.value is Bool), let n = raw.value as? Int, n == {i} else {{ throw ValidationError.outOfRange(\"value\", \"must be {i}\") }}")
        }
        LiteralValue::Number(n) => {
            let b = format_number(*n);
            format!("        guard !(raw.value is Bool), let d = raw.value as? Double, d == {b} else {{ throw ValidationError.outOfRange(\"value\", \"must be {b}\") }}")
        }
        LiteralValue::String(s) => {
            let escaped = swift_escape(s);
            format!("        guard let s = raw.value as? String, s == \"{escaped}\" else {{ throw ValidationError.outOfRange(\"value\", \"must be \\\"{escaped}\\\"\") }}")
        }
        LiteralValue::Null => {
            "        guard raw.value is NSNull else { throw ValidationError.outOfRange(\"value\", \"must be null\") }".to_string()
        }
    };

    format!(
        "struct {name}: Codable {{\n    let value: AnyCodable\n\n    // @validate\n    init(from decoder: Decoder) throws {{\n        let container = try decoder.singleValueContainer()\n        let raw = try container.decode(AnyCodable.self)\n        value = raw\n{check}\n    }}\n\n    func encode(to encoder: Encoder) throws {{\n        var container = encoder.singleValueContainer()\n        try container.encode(value)\n    }}\n}}"
    )
}

fn emit_mixed_enum_wrapper(name: &str, lits: &[LiteralValue]) -> String {
    let mut checks = Vec::new();
    for lit in lits {
        let check = match lit {
            LiteralValue::Bool(b) => {
                let val = if *b { "true" } else { "false" };
                format!("(raw.value as? Bool) == {val}")
            }
            LiteralValue::Integer(i) => {
                format!("(!(raw.value is Bool) && ((raw.value as? Int) == {i} || (raw.value as? Double) == Double({i})))")
            }
            LiteralValue::Number(n) => {
                let b = format_number(*n);
                format!("(!(raw.value is Bool) && ((raw.value as? Double) == {b} || (raw.value as? Int).map(Double.init) == {b}))")
            }
            LiteralValue::String(s) => {
                format!("(raw.value as? String) == \"{}\"", swift_escape(s))
            }
            LiteralValue::Null => "raw.value is NSNull".to_string(),
        };
        checks.push(check);
    }

    let condition = checks.join(" || ");
    format!(
        "struct {name}: Codable {{\n    let value: AnyCodable\n\n    // @validate\n    init(from decoder: Decoder) throws {{\n        let container = try decoder.singleValueContainer()\n        let raw = try container.decode(AnyCodable.self)\n        value = raw\n        guard {condition} else {{ throw ValidationError.outOfRange(\"value\", \"must be one of the allowed values\") }}\n    }}\n\n    func encode(to encoder: Encoder) throws {{\n        var container = encoder.singleValueContainer()\n        try container.encode(value)\n    }}\n}}"
    )
}

