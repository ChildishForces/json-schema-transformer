use std::cell::RefCell;
use std::sync::atomic::{AtomicUsize, Ordering};
use crate::ir::*;
use crate::util::to_pascal_case;
use super::Emitter;

static SUB_SCHEMA_COUNTER: AtomicUsize = AtomicUsize::new(0);

thread_local! {
    /// Per-file type prefix applied to $defs type names so that many generated
    /// files can be compiled into a single Swift module without collisions.
    static TYPE_PREFIX: RefCell<String> = const { RefCell::new(String::new()) };
}

/// Shared helper type names that appear in type signatures (so they cannot be
/// `private`) and must instead be prefixed per-file to avoid duplicate symbols
/// when compiling many generated files into one module.
const SIGNATURE_HELPER_TYPES: &[&str] = &[
    "EmailAddress",
    "HostnameString",
    "IPv4Address",
    "IPv6Address",
    "IPAddress",
    "TimeString",
    "DurationString",
    "Base64String",
];

pub struct SwiftEmitter;

impl Emitter for SwiftEmitter {
    fn extension(&self) -> &str {
        "swift"
    }

    fn emit(
        &self,
        converted: &ConvertedSchema,
        name: &str,
        namespace: &str,
        version: u32,
    ) -> String {
        // Reset global sub-schema counter for each emit
        SUB_SCHEMA_COUNTER.store(0, Ordering::Relaxed);
        let pascal = to_pascal_case(name);
        // Prefix $defs type names per file so many files can share one module.
        TYPE_PREFIX.with(|p| *p.borrow_mut() = format!("{pascal}V{version}"));
        let mut out = String::new();

        out.push_str(&format!(
            "// Generated by event-registry\n// {namespace}/{name}@{version}\n// DO NOT EDIT — changes will be overwritten on next pull\n\n"
        ));
        out.push_str("import Foundation\n\n");

        // Emit body first to detect which helpers are needed
        let mut body = String::new();
        for def in &converted.defs {
            let safe_name = sanitize_swift_name(&def.name);
            let code = emit_struct(&safe_name, &def.schema, &converted.defs);
            // For recursive types, Swift structs can't form cycles — use class
            let code = if def.is_recursive {
                code.replacen(&format!("struct {safe_name}:"), &format!("final class {safe_name}:"), 1)
            } else {
                code
            };
            body.push_str(&code);
            body.push_str("\n\n");
        }
        body.push_str(&emit_struct(
            &format!("{pascal}V{version}Data"),
            &converted.root,
            &converted.defs,
        ));
        body.push('\n');

        // Emit validation error enum if any validating types are used
        let mut helpers = SwiftHelpers::default();
        helpers.detect(&body);

        if helpers.needs_any() {
            out.push_str(&helpers.emit_validation_error());
            out.push('\n');
        }
        if helpers.needs_email {
            out.push_str(EMAIL_ADDRESS_HELPER);
            out.push('\n');
        }
        if helpers.needs_hostname {
            out.push_str(HOSTNAME_HELPER);
            out.push('\n');
        }
        if helpers.needs_ipv4 {
            out.push_str(IPV4_ADDRESS_HELPER);
            out.push('\n');
        }
        if helpers.needs_ipv6 {
            out.push_str(IPV6_ADDRESS_HELPER);
            out.push('\n');
        }
        if helpers.needs_ip {
            // IPAddress depends on IPv4Address and IPv6Address
            if !helpers.needs_ipv4 {
                out.push_str(IPV4_ADDRESS_HELPER);
                out.push('\n');
            }
            if !helpers.needs_ipv6 {
                out.push_str(IPV6_ADDRESS_HELPER);
                out.push('\n');
            }
            out.push_str(IP_ADDRESS_HELPER);
            out.push('\n');
        }
        if helpers.needs_time {
            out.push_str(TIME_STRING_HELPER);
            out.push('\n');
        }
        if helpers.needs_duration {
            out.push_str(DURATION_STRING_HELPER);
            out.push('\n');
        }
        if helpers.needs_base64 {
            out.push_str(BASE64_STRING_HELPER);
            out.push('\n');
        }
        if helpers.needs_serialize_any {
            out.push_str(SERIALIZE_ANY_HELPER);
            out.push('\n');
        }

        out.push_str(&body);

        // Prefix signature-visible helper types (EmailAddress, TimeString, …)
        // per file: they appear in stored-property/typealias signatures of the
        // internal root type, so they cannot be `private` — renaming them keeps
        // every generated file safe to compile into one shared module.
        let prefix = format!("{pascal}V{version}");
        for helper in SIGNATURE_HELPER_TYPES {
            if out.contains(helper) {
                out = out.replace(helper, &format!("{prefix}{helper}"));
            }
        }
        out
    }
}

// ── Helper detection ─────────────────────────────────────────────────────────

#[derive(Default)]
struct SwiftHelpers {
    needs_email: bool,
    needs_hostname: bool,
    needs_ipv4: bool,
    needs_ipv6: bool,
    needs_ip: bool,
    needs_time: bool,
    needs_duration: bool,
    needs_base64: bool,
    needs_numeric_validation: bool,
    needs_serialize_any: bool,
}

impl SwiftHelpers {
    fn detect(&mut self, body: &str) {
        self.needs_email = body.contains("EmailAddress");
        self.needs_hostname = body.contains("HostnameString");
        self.needs_ipv4 = body.contains("IPv4Address");
        self.needs_ipv6 = body.contains("IPv6Address");
        self.needs_ip = body.contains("IPAddress");
        self.needs_time = body.contains("TimeString");
        self.needs_duration = body.contains("DurationString");
        self.needs_base64 = body.contains("Base64String");
        self.needs_numeric_validation = body.contains("// @validate");
        self.needs_serialize_any = body.contains("_serializeAny");
    }

    fn needs_any(&self) -> bool {
        self.needs_email
            || self.needs_hostname
            || self.needs_ipv4
            || self.needs_ipv6
            || self.needs_ip
            || self.needs_time
            || self.needs_duration
            || self.needs_base64
            || self.needs_numeric_validation
    }

    fn emit_validation_error(&self) -> String {
        let mut cases = Vec::new();
        let mut descriptions = Vec::new();

        if self.needs_email {
            cases.push("    case invalidEmail(String)");
            descriptions.push(r#"        case .invalidEmail(let v): "Invalid email address: \(v)""#);
        }
        if self.needs_hostname {
            cases.push("    case invalidHostname(String)");
            descriptions.push(r#"        case .invalidHostname(let v): "Invalid hostname: \(v)""#);
        }
        if self.needs_ipv4 || self.needs_ip {
            cases.push("    case invalidIPv4(String)");
            descriptions.push(r#"        case .invalidIPv4(let v): "Invalid IPv4 address: \(v)""#);
        }
        if self.needs_ipv6 || self.needs_ip {
            cases.push("    case invalidIPv6(String)");
            descriptions.push(r#"        case .invalidIPv6(let v): "Invalid IPv6 address: \(v)""#);
        }
        if self.needs_ip {
            cases.push("    case invalidIP(String)");
            descriptions.push(r#"        case .invalidIP(let v): "Invalid IP address: \(v)""#);
        }
        if self.needs_time {
            cases.push("    case invalidTime(String)");
            descriptions.push(r#"        case .invalidTime(let v): "Invalid time: \(v)""#);
        }
        if self.needs_duration {
            cases.push("    case invalidDuration(String)");
            descriptions.push(r#"        case .invalidDuration(let v): "Invalid duration: \(v)""#);
        }
        if self.needs_base64 {
            cases.push("    case invalidBase64(String)");
            descriptions.push(r#"        case .invalidBase64(let v): "Invalid base64: \(v)""#);
        }
        if self.needs_numeric_validation {
            cases.push("    case outOfRange(String, String)");
            descriptions.push(r#"        case .outOfRange(let field, let detail): "\(field): \(detail)""#);
        }

        format!(
            "private enum ValidationError: LocalizedError {{\n{}\n\n    var errorDescription: String? {{\n        switch self {{\n{}\n        }}\n    }}\n}}\n",
            cases.join("\n"),
            descriptions.join("\n"),
        )
    }
}

