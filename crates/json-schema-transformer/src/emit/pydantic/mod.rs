// ── Constrained array emission ──────────────────────────────────────────────

fn emit_constrained_array(
    name: &str,
    arr: &ArraySchema,
    defs: &[DefEntry],
    counter: &mut usize,
) -> String {
    let item_type = py_type(&arr.items, defs);
    let base_type = format!("list[{item_type}]");
    let constraints = field_constraints(&SchemaIr::Array(arr.clone()));

    let mut out = String::new();
    let mut validator_checks = Vec::new();

    // uniqueItems
    if arr.unique_items {
        validator_checks.push(
            "    if len(set(json.dumps(x, sort_keys=True, default=str) for x in v)) != len(v):\n        raise ValueError('uniqueItems')"
                .to_string(),
        );
    }

    // contains
    if let Some(contains) = &arr.contains {
        let (sub_preamble, sub_type) =
            emit_sub_schema("contains", &contains.schema, defs, counter);
        if !sub_preamble.is_empty() {
            out.push_str(&sub_preamble);
            out.push('\n');
        }
        *counter += 1;
        let ta_name = format!("_contains_ta_{}", *counter);
        out.push_str(&format!("{ta_name} = TypeAdapter({sub_type})\n"));

        let min = contains.min_contains.unwrap_or(1);
        validator_checks.push(format!(
            "    _match_count = sum(1 for x in v if _try_validate({ta_name}, x))"
        ));
        validator_checks.push(format!(
            "    if _match_count < {min}:\n        raise ValueError('must contain at least {min} matching items')"
        ));
        if let Some(max) = contains.max_contains {
            validator_checks.push(format!(
                "    if _match_count > {max}:\n        raise ValueError('must contain at most {max} matching items')"
            ));
        }

        // Add the _try_validate helper if not already present
        out.push_str(&format!("\n{TRY_VALIDATE_HELPER}\n"));
    }

    if validator_checks.is_empty() {
        // Just use annotated type
        if constraints.is_empty() {
            out.push_str(&format!("{name} = {base_type}"));
        } else {
            out.push_str(&format!(
                "{name} = Annotated[{base_type}, Field({constraints})]"
            ));
        }
    } else {
        *counter += 1;
        let fn_name = format!("_validate_arr_{}", *counter);

        out.push_str(&format!("def {fn_name}(v):\n"));
        out.push_str("    if not isinstance(v, (list, tuple)):\n        return v\n");
        for check in &validator_checks {
            out.push_str(check);
            out.push('\n');
        }
        out.push_str("    return v\n\n");

        if constraints.is_empty() {
            out.push_str(&format!(
                "{name} = Annotated[{base_type}, BeforeValidator({fn_name})]"
            ));
        } else {
            out.push_str(&format!(
                "{name} = Annotated[{base_type}, Field({constraints}), BeforeValidator({fn_name})]"
            ));
        }
    }

    out
}

// ── Tuple emission ──────────────────────────────────────────────────────────

fn emit_constrained_tuple(
    name: &str,
    tuple: &TupleSchema,
    defs: &[DefEntry],
    counter: &mut usize,
) -> String {
    let mut out = String::new();
    let mut checks = Vec::new();

    // Item type adapters for each prefix item
    let mut item_tas = Vec::new();
    for (i, item) in tuple.items.iter().enumerate() {
        let (sub_preamble, sub_type) = emit_sub_schema("ti", item, defs, counter);
        if !sub_preamble.is_empty() {
            out.push_str(&sub_preamble);
            out.push('\n');
        }
        *counter += 1;
        let ta_name = format!("_ti_ta_{}", *counter);
        out.push_str(&format!("{ta_name} = TypeAdapter({sub_type})\n"));
        item_tas.push((i, ta_name));
    }

    // Rest type adapter
    let rest_ta = match &tuple.rest {
        None => None,
        Some(rest) if matches!(rest.as_ref(), SchemaIr::Any) => None,
        Some(rest) => {
            let (sub_preamble, sub_type) = emit_sub_schema("tr", rest, defs, counter);
            if !sub_preamble.is_empty() {
                out.push_str(&sub_preamble);
                out.push('\n');
            }
            *counter += 1;
            let ta_name = format!("_tr_ta_{}", *counter);
            out.push_str(&format!("{ta_name} = TypeAdapter({sub_type})\n"));
            Some(ta_name)
        }
    };

    // Validate prefix items
    for (i, ta) in &item_tas {
        checks.push(format!(
            "    if len(v) > {i}:\n        {ta}.validate_python(v[{i}])"
        ));
    }

    // Validate rest items
    let prefix_count = tuple.items.len();
    if let Some(ref rest_ta) = rest_ta {
        checks.push(format!(
            "    for _i in range({prefix_count}, len(v)):\n        {rest_ta}.validate_python(v[_i])"
        ));
    } else if tuple.rest.is_none() {
        // items: false — no additional items beyond prefix
        checks.push(format!(
            "    if len(v) > {prefix_count}:\n        raise ValueError('too many items')"
        ));
    }

    // minItems / maxItems
    if let Some(min) = tuple.min_items {
        checks.push(format!(
            "    if len(v) < {min}:\n        raise ValueError('minItems')"
        ));
    }
    if let Some(max) = tuple.max_items {
        checks.push(format!(
            "    if len(v) > {max}:\n        raise ValueError('maxItems')"
        ));
    }

    // uniqueItems
    if tuple.unique_items {
        checks.push(
            "    if len(set(json.dumps(x, sort_keys=True, default=str) for x in v)) != len(v):\n        raise ValueError('uniqueItems')"
                .to_string(),
        );
    }

    // contains
    if let Some(contains) = &tuple.contains {
        let (sub_preamble, sub_type) =
            emit_sub_schema("tc", &contains.schema, defs, counter);
        if !sub_preamble.is_empty() {
            out.push_str(&sub_preamble);
            out.push('\n');
        }
        *counter += 1;
        let ta_name = format!("_tc_ta_{}", *counter);
        out.push_str(&format!("{ta_name} = TypeAdapter({sub_type})\n"));

        let min = contains.min_contains.unwrap_or(1);
        checks.push(format!(
            "    _match_count = sum(1 for x in v if _try_validate({ta_name}, x))"
        ));
        checks.push(format!(
            "    if _match_count < {min}:\n        raise ValueError('must contain at least {min} matching items')"
        ));
        if let Some(max) = contains.max_contains {
            checks.push(format!(
                "    if _match_count > {max}:\n        raise ValueError('must contain at most {max} matching items')"
            ));
        }
    }

    *counter += 1;
    let fn_name = format!("_validate_tuple_{}", *counter);

    out.push_str(&format!("\ndef {fn_name}(v):\n"));
    out.push_str("    if not isinstance(v, (list, tuple)):\n        return v\n");
    for check in &checks {
        out.push_str(check);
        out.push('\n');
    }
    out.push_str("    return v\n\n");
    out.push_str(&format!(
        "{name} = Annotated[list, BeforeValidator({fn_name})]"
    ));

    out
}

// ── Never emission ──────────────────────────────────────────────────────────

fn emit_never(name: &str, counter: &mut usize) -> String {
    *counter += 1;
    let fn_name = format!("_validate_never_{}", *counter);
    format!(
        "def {fn_name}(v):\n    raise ValueError('schema rejects all values')\n\n{name} = Annotated[Any, BeforeValidator({fn_name})]"
    )
}

// ── Interpreted emission ────────────────────────────────────────────────────

/// Embed the raw schema + remote documents as JSON and validate with the
/// emitted `_jsi_validate` interpreter (see JSI_PY_HELPER).
fn emit_interpreted(
    name: &str,
    schema: &serde_json::Value,
    remotes: &[(String, serde_json::Value)],
    counter: &mut usize,
) -> String {
    *counter += 1;
    let n = *counter;

    // Double-encode: json.loads of a JSON string literal. serde_json only emits
    // \", \\ and \uXXXX escapes, all of which mean the same thing in a Python
    // double-quoted string literal.
    let schema_json = serde_json::to_string(schema).unwrap_or_else(|_| "true".to_string());
    let schema_literal =
        serde_json::to_string(&serde_json::Value::String(schema_json)).unwrap();
    let remotes_json = {
        let map: serde_json::Map<String, serde_json::Value> = remotes
            .iter()
            .map(|(k, v)| (k.clone(), v.clone()))
            .collect();
        serde_json::to_string(&serde_json::Value::Object(map))
            .unwrap_or_else(|_| "{}".to_string())
    };
    let remotes_literal =
        serde_json::to_string(&serde_json::Value::String(remotes_json)).unwrap();

    format!(
        "_jsi_schema_{n} = json.loads({schema_literal})\n\
         _jsi_remotes_{n} = json.loads({remotes_literal})\n\
         \n\
         def _jsi_check_{n}(v):\n    \
             if not _jsi_validate(_jsi_schema_{n}, _jsi_remotes_{n}, v):\n        \
                 raise ValueError('does not match schema')\n    \
             return v\n\
         \n\
         {name} = Annotated[Any, BeforeValidator(_jsi_check_{n})]"
    )
}

// ── Sub-schema emission ─────────────────────────────────────────────────────

fn emit_sub_schema(
    prefix: &str,
    ir: &SchemaIr,
    defs: &[DefEntry],
    counter: &mut usize,
) -> (String, String) {
    match ir {
        SchemaIr::Object(_)
        | SchemaIr::TypeGuarded(_)
        | SchemaIr::Not { .. }
        | SchemaIr::Conditional { .. }
        | SchemaIr::ConstEqual(_)
        | SchemaIr::ComplexEnum(_)
        | SchemaIr::MixedEnum(_)
        | SchemaIr::Literal(_)
        | SchemaIr::ExclusiveUnion(_)
        | SchemaIr::Never
        | SchemaIr::Tuple(_)
        | SchemaIr::Enum(_) => {
            *counter += 1;
            let sub_name = format!("_{prefix}_{}", *counter);
            let def = emit_definition(&sub_name, ir, defs, counter);
            (format!("{def}\n"), sub_name)
        }
        SchemaIr::Intersection(members) if members.len() == 1 => {
            emit_sub_schema(prefix, &members[0], defs, counter)
        }
        SchemaIr::Intersection(members) if members.len() > 1 => {
            *counter += 1;
            let sub_name = format!("_{prefix}_{}", *counter);
            let def = emit_definition(&sub_name, ir, defs, counter);
            (format!("{def}\n"), sub_name)
        }
        SchemaIr::Union(members) if members.len() > 1 => {
            *counter += 1;
            let sub_name = format!("_{prefix}_{}", *counter);
            let def = emit_definition(&sub_name, ir, defs, counter);
            (format!("{def}\n"), sub_name)
        }
        SchemaIr::Array(arr) if arr.unique_items || arr.contains.is_some() => {
            *counter += 1;
            let sub_name = format!("_{prefix}_{}", *counter);
            let def = emit_definition(&sub_name, ir, defs, counter);
            (format!("{def}\n"), sub_name)
        }
        _ => (String::new(), annotated_type(ir, defs)),
    }
}

// ── Type mapping ────────────────────────────────────────────────────────────

fn py_type(ir: &SchemaIr, defs: &[DefEntry]) -> String {
    match ir {
        // Strict scalars: JSON Schema forbids pydantic's lax coercions
        // ("1" -> 1.0, True -> 1, 1 -> "1"), so every scalar annotation
        // carries its type-check BeforeValidator even when nested.
        SchemaIr::String(_) => "Annotated[str, BeforeValidator(_check_str)]".to_string(),
        SchemaIr::Number(_) => "Annotated[float, BeforeValidator(_check_number)]".to_string(),
        SchemaIr::Integer(_) => "Annotated[int, BeforeValidator(_check_int)]".to_string(),
        SchemaIr::Boolean => "Annotated[bool, BeforeValidator(_check_bool)]".to_string(),
        SchemaIr::Null => "None".to_string(),
        // Interpreted is handled in emit_definition (root-level only); as a bare
        // type annotation it degrades to Any.
        SchemaIr::Any | SchemaIr::Unknown | SchemaIr::Interpreted { .. } => "Any".to_string(),
        SchemaIr::Never => "Any".to_string(),

        SchemaIr::Literal(lit) => match lit {
            LiteralValue::String(s) => format!("Literal[\"{}\"]", escape_string(s)),
            LiteralValue::Number(n) => format!("Literal[{n}]"),
            LiteralValue::Integer(i) => format!("Literal[{i}]"),
            LiteralValue::Bool(b) => {
                format!("Literal[{}]", if *b { "True" } else { "False" })
            }
            LiteralValue::Null => "None".to_string(),
        },

        SchemaIr::ConstEqual(_) => "Any".to_string(),

        SchemaIr::Enum(cases) => {
            let parts: Vec<String> = cases
                .iter()
                .map(|c| format!("\"{}\"", escape_string(c)))
                .collect();
            format!("Literal[{}]", parts.join(", "))
        }

        SchemaIr::MixedEnum(lits) => {
            let parts: Vec<String> = lits.iter().map(|l| py_literal_value(l)).collect();
            format!("Literal[{}]", parts.join(", "))
        }

        SchemaIr::ComplexEnum(_) => "Any".to_string(),

        SchemaIr::Array(arr) => {
            format!("list[{}]", py_type(&arr.items, defs))
        }

        SchemaIr::Tuple(tuple) => {
            let parts: Vec<String> =
                tuple.items.iter().map(|i| py_type(i, defs)).collect();
            if let Some(rest) = &tuple.rest {
                let rest_type = py_type(rest, defs);
                format!("tuple[{}, *tuple[{rest_type}, ...]]", parts.join(", "))
            } else {
                format!("tuple[{}]", parts.join(", "))
            }
        }

        SchemaIr::Object(_) => "dict[str, Any]".to_string(),

        SchemaIr::Record(rec) => {
            format!("dict[str, {}]", py_type(&rec.value, defs))
        }

        SchemaIr::Union(members) | SchemaIr::ExclusiveUnion(members) => {
            let parts: Vec<String> =
                members.iter().map(|m| py_type(m, defs)).collect();
            format!("Union[{}]", parts.join(", "))
        }

        SchemaIr::Intersection(_) => "Any".to_string(),

        SchemaIr::Nullable(inner) => format!("Optional[{}]", py_type(inner, defs)),
        SchemaIr::Optional(inner) => format!("Optional[{}]", py_type(inner, defs)),
        SchemaIr::Default(inner, _) => py_type(inner, defs),
        SchemaIr::Describe(inner, _) => py_type(inner, defs),
        SchemaIr::Not { base, .. } => py_type(base, defs),
        SchemaIr::Conditional { base, .. } => py_type(base, defs),
        SchemaIr::TypeGuarded(_) => "Any".to_string(),

        SchemaIr::Ref(name) | SchemaIr::Lazy(name) => format!("\"{name}\""),
    }
}

fn py_literal_value(lit: &LiteralValue) -> String {
    match lit {
        LiteralValue::String(s) => format!("\"{}\"", escape_string(s)),
        LiteralValue::Number(n) => format!("{n}"),
        LiteralValue::Integer(i) => format!("{i}"),
        LiteralValue::Bool(b) => {
            if *b { "True" } else { "False" }.to_string()
        }
        LiteralValue::Null => "None".to_string(),
    }
}

fn field_constraints(ir: &SchemaIr) -> String {
    let mut parts = Vec::new();

    match ir {
        SchemaIr::String(c) => {
            if let Some(min) = c.min_length {
                parts.push(format!("min_length={min}"));
            }
            if let Some(max) = c.max_length {
                parts.push(format!("max_length={max}"));
            }
            if let Some(pat) = &c.pattern {
                parts.push(format!("pattern=r\"{}\"", pat));
            }
        }
        SchemaIr::Number(c) | SchemaIr::Integer(c) => {
            let is_integer = matches!(ir, SchemaIr::Integer(_));
            if let Some(v) = c.minimum {
                parts.push(format!("ge={}", format_py_number(v)));
            }
            if let Some(v) = c.maximum {
                parts.push(format!("le={}", format_py_number(v)));
            }
            if let Some(v) = c.exclusive_minimum {
                parts.push(format!("gt={}", format_py_number(v)));
            }
            if let Some(v) = c.exclusive_maximum {
                parts.push(format!("lt={}", format_py_number(v)));
            }
            if let Some(v) = c.multiple_of {
                // Pydantic requires multiple_of on int fields to be integer-coercible
                if !is_integer || v == v.trunc() {
                    parts.push(format!("multiple_of={}", format_py_number(v)));
                }
            }
        }
        SchemaIr::Array(a) => {
            if let Some(min) = a.min_items {
                parts.push(format!("min_length={min}"));
            }
            if let Some(max) = a.max_items {
                parts.push(format!("max_length={max}"));
            }
        }
        SchemaIr::Describe(inner, desc) => {
            parts.push(format!("description=\"{}\"", escape_string(desc)));
            let inner_constraints = field_constraints(inner);
            if !inner_constraints.is_empty() {
                parts.push(inner_constraints);
            }
        }
        SchemaIr::Default(inner, _) => {
            let inner_constraints = field_constraints(inner);
            if !inner_constraints.is_empty() {
                parts.push(inner_constraints);
            }
        }
        _ => {}
    }

    parts.join(", ")
}

fn format_py_number(n: f64) -> String {
    if n == n.trunc() && n.abs() < 1e15 {
        format!("{}", n as i64)
    } else {
        format!("{n}")
    }
}

