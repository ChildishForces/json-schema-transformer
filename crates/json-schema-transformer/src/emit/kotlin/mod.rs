fn kotlin_type(ir: &SchemaIr, defs: &[DefEntry], prefix: &str) -> String {
    match ir {
        SchemaIr::String(_) => "String".to_string(),
        SchemaIr::Number(_) => "Double".to_string(),
        SchemaIr::Integer(_) => "Int".to_string(),
        SchemaIr::Boolean => "Boolean".to_string(),
        SchemaIr::Null => "Nothing?".to_string(),
        // TODO(kotlin-interpreter): validate via embedded spec interpreter
        SchemaIr::Any | SchemaIr::Unknown | SchemaIr::Interpreted { .. } => "JsonElement".to_string(),
        SchemaIr::Never => "Nothing".to_string(),

        SchemaIr::Literal(lit) => match lit {
            LiteralValue::String(_) => "String".to_string(),
            LiteralValue::Number(_) => "Double".to_string(),
            LiteralValue::Integer(_) => "Int".to_string(),
            LiteralValue::Bool(_) => "Boolean".to_string(),
            LiteralValue::Null => "Nothing?".to_string(),
        },

        SchemaIr::ConstEqual(_) | SchemaIr::ComplexEnum(_) => "JsonElement".to_string(),
        SchemaIr::Enum(_) => "String".to_string(),
        SchemaIr::MixedEnum(_) => "JsonElement".to_string(),

        SchemaIr::Array(arr) => format!("List<{}>", kotlin_type(&arr.items, defs, prefix)),
        SchemaIr::Tuple(_) => "List<JsonElement>".to_string(),
        SchemaIr::Object(_) => "JsonObject".to_string(),
        SchemaIr::Record(rec) => format!("Map<String, {}>", kotlin_type(&rec.value, defs, prefix)),

        SchemaIr::Union(members) | SchemaIr::ExclusiveUnion(members) => {
            if members.len() == 2 {
                let non_null: Vec<_> = members
                    .iter()
                    .filter(|m| !matches!(m, SchemaIr::Null))
                    .collect();
                if non_null.len() == 1 {
                    return format!("{}?", kotlin_type(non_null[0], defs, prefix));
                }
            }
            "JsonElement".to_string()
        }

        SchemaIr::Intersection(_) => "JsonElement".to_string(),
        SchemaIr::Nullable(inner) => format!("{}?", kotlin_type(inner, defs, prefix)),
        SchemaIr::Optional(inner) => format!("{}?", kotlin_type(inner, defs, prefix)),
        SchemaIr::Default(inner, _) => kotlin_type(inner, defs, prefix),
        SchemaIr::Describe(inner, _) => kotlin_type(inner, defs, prefix),
        SchemaIr::Not { base, .. } => kotlin_type(base, defs, prefix),
        SchemaIr::Conditional { base, .. } => kotlin_type(base, defs, prefix),
        SchemaIr::TypeGuarded(_) => "JsonElement".to_string(),
        SchemaIr::Ref(name) | SchemaIr::Lazy(name) => sanitize_kotlin_name(name, prefix),
    }
}

fn format_kt_number(n: f64) -> String {
    if n == n.trunc() && n.abs() < 1e15 {
        format!("{}.0", n as i64)
    } else {
        format!("{n}")
    }
}

/// Human-friendly number rendering for diagnostic messages: integral values
/// print without the trailing ".0" (check expressions still use
/// `format_kt_number`, which must produce a valid Kotlin Double literal).
fn format_msg_number(n: f64) -> String {
    if n.fract() == 0.0 && n.abs() < 9.007199254740992e15 {
        format!("{}", n as i64)
    } else {
        format!("{n}")
    }
}

/// Convert to lowerCamelCase (Kotlin convention).
fn to_camel_case(s: &str) -> String {
    if !s.contains(|c: char| !c.is_ascii_alphanumeric())
        && s.chars().next().is_some_and(|c| c.is_ascii_lowercase())
    {
        let result = s.to_string();
        return if is_kotlin_keyword(&result) {
            format!("`{result}`")
        } else {
            result
        };
    }

    let parts: Vec<&str> = s
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
        .collect();

    if parts.is_empty() {
        return s.to_string();
    }

    let mut result = parts[0].to_lowercase();
    for part in &parts[1..] {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            result.push(first.to_ascii_uppercase());
            result.extend(chars);
        }
    }

    if is_kotlin_keyword(&result) {
        format!("`{result}`")
    } else {
        result
    }
}

fn is_kotlin_keyword(s: &str) -> bool {
    matches!(
        s,
        "as" | "break" | "class" | "continue" | "do" | "else" | "false" | "for" | "fun"
            | "if" | "in" | "interface" | "is" | "null" | "object" | "package" | "return"
            | "super" | "this" | "throw" | "true" | "try" | "typealias" | "typeof" | "val"
            | "var" | "when" | "while"
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::emit::SharedHelpers;
    use crate::Converter;
    use serde_json::json;

    fn order_item_schema() -> serde_json::Value {
        json!({
            "type": "object",
            "properties": {
                "id": {"type": "string"},
                "quantity": {"type": "integer", "minimum": 1}
            },
            "required": ["id", "quantity"],
            "additionalProperties": false
        })
    }

    fn emit_opts(schema: &serde_json::Value, options: &EmitOptions) -> String {
        let converted = Converter::convert(schema).unwrap();
        KotlinEmitter.emit_with_options(&converted, "sample", options)
    }

    #[test]
    fn default_emit_conforms_to_mangled_validatable() {
        let out = emit_opts(&order_item_schema(), &EmitOptions::default());
        // Inline mode: interface declared per file under a mangled name.
        assert!(out.contains("interface _SampleJstValidatable"), "{out}");
        assert!(out.contains("class Sample(val element: JsonElement) : _SampleJstValidatable {"), "{out}");
        assert!(out.contains("override fun validate()"), "{out}");
        assert!(out.contains("override fun toValidatedJson(): String"), "{out}");
        // Typed construction via companion invoke, unvalidated by design.
        assert!(out.contains("operator fun invoke("), "{out}");
        assert!(out.contains("quantity: Int"), "{out}");
        // Immutable by default.
        assert!(!out.contains("var element"), "{out}");
    }

    #[test]
    fn mutable_emit_uses_var_properties() {
        let opts = EmitOptions { mutable: true, ..EmitOptions::default() };
        let wrapper = emit_opts(&order_item_schema(), &opts);
        assert!(wrapper.contains("class Sample(var element: JsonElement)"), "{wrapper}");

        // Fully-typed all-required object → data class path.
        let plain = json!({
            "type": "object",
            "properties": {"id": {"type": "string"}},
            "required": ["id"]
        });
        let dc = emit_opts(&plain, &opts);
        assert!(dc.contains("var id: String"), "{dc}");
        let dc_default = emit_opts(&plain, &EmitOptions::default());
        assert!(dc_default.contains("val id: String"), "{dc_default}");
        assert!(dc_default.contains(") : _SampleJstValidatable {"), "{dc_default}");
    }

    #[test]
    fn shared_mode_imports_canonical_interface_and_reports_need() {
        let converted = Converter::convert(&order_item_schema()).unwrap();
        let options = EmitOptions {
            helpers: Some(SharedHelpers::new("JstHelpers.kt")),
            mutable: false,
        };
        let (out, needs) = KotlinEmitter.emit_collecting(&converted, "sample", &options);
        assert!(needs.contains("validatable"), "{needs:?}");
        assert!(out.contains("import jst.helpers._JstValidatable"), "{out}");
        assert!(out.contains(": _JstValidatable {"), "{out}");
        assert!(!out.contains("interface _JstValidatable"), "{out}");

        let helpers = KotlinEmitter.helpers_content_for(&needs).unwrap();
        assert!(helpers.contains("interface _JstValidatable"), "{helpers}");
        // Public on purpose: generated public classes implement it.
        assert!(!helpers.contains("internal interface _JstValidatable"), "{helpers}");
    }

    #[test]
    fn enums_and_typealiases_skip_validatable() {
        let out = emit_opts(&json!({"enum": ["a", "b"]}), &EmitOptions::default());
        assert!(out.contains("enum class Sample"), "{out}");
        assert!(!out.contains("JstValidatable"), "{out}");
        assert!(!out.contains("import kotlinx.serialization.encodeToString"), "{out}");
        // No wrapper serializer → no error classes either.
        assert!(!out.contains("JstIssue"), "{out}");
    }

    #[test]
    fn wrapper_collects_all_issues_with_mangled_inline_names() {
        let out = emit_opts(&order_item_schema(), &EmitOptions::default());
        // Inline mode: issue/exception classes are declared per file under
        // mangled names and the serializer collects instead of throwing.
        assert!(out.contains("data class _SampleJstIssue(val path: String, val message: String)"), "{out}");
        assert!(out.contains("class _SampleJstValidationException(val issues: List<_SampleJstIssue>)"), "{out}");
        assert!(out.contains("val issues = mutableListOf<_SampleJstIssue>()"), "{out}");
        assert!(out.contains("if (issues.isNotEmpty()) throw _SampleJstValidationException(issues)"), "{out}");
        // Multiple independent constraint pushes, each with a pointer path.
        assert!(out.contains("issues.add(_SampleJstIssue(path + \"/id\", \"required property is missing\"))"), "{out}");
        assert!(out.contains("issues.add(_SampleJstIssue(path + \"/quantity\", \"required property is missing\"))"), "{out}");
        assert!(out.contains("\"must be >= 1\""), "{out}");
        assert!(out.contains("issues.add(_SampleJstIssue(path + \"/\" + _jstPtr(k), \"unexpected property\"))"), "{out}");
        // No first-failure aborts left in the wrapper serializer.
        assert!(!out.contains("require("), "{out}");
    }

    #[test]
    fn shared_mode_uses_canonical_error_names_and_tailors_helper() {
        let converted = Converter::convert(&order_item_schema()).unwrap();
        let options = EmitOptions {
            helpers: Some(SharedHelpers::new("JstHelpers.kt")),
            mutable: false,
        };
        let (out, needs) = KotlinEmitter.emit_collecting(&converted, "sample", &options);
        assert!(needs.contains("error"), "{needs:?}");
        assert!(out.contains("import jst.helpers.JstIssue"), "{out}");
        assert!(out.contains("import jst.helpers.JstValidationException"), "{out}");
        assert!(out.contains("import jst.helpers._jstPtr"), "{out}");
        assert!(out.contains("val issues = mutableListOf<JstIssue>()"), "{out}");
        assert!(!out.contains("_SampleJstIssue"), "{out}");

        let helpers = KotlinEmitter.helpers_content_for(&needs).unwrap();
        // Classes stay public (user code catches the exception type);
        // only the pointer-escape helper is internalized.
        assert!(helpers.contains("data class JstIssue"), "{helpers}");
        assert!(helpers.contains("class JstValidationException"), "{helpers}");
        assert!(helpers.contains("kotlinx.serialization.SerializationException"), "{helpers}");
        assert!(helpers.contains("internal fun _jstPtr"), "{helpers}");
        assert!(!helpers.contains("internal data class JstIssue"), "{helpers}");
    }

    #[test]
    fn unique_items_reports_every_duplicate_index() {
        let out = emit_opts(
            &json!({"type": "array", "items": {"type": "string"}, "uniqueItems": true}),
            &EmitOptions::default(),
        );
        assert!(out.contains("for ((i, item) in arr.withIndex()) { if (!_seen.add(_canonicalize(item)))"), "{out}");
        assert!(out.contains("issues.add(_SampleJstIssue(path + \"/\" + i, \"duplicate item\"))"), "{out}");
    }

    #[test]
    fn union_verdicts_stay_single_issue() {
        let out = emit_opts(
            &json!({"oneOf": [{"type": "string"}, {"type": "integer"}]}),
            &EmitOptions::default(),
        );
        assert!(out.contains("val branchResults = listOf("), "{out}");
        assert!(out.contains("must match exactly one of the expected schemas (oneOf)"), "{out}");
        // Branch verdicts run the collector privately and only report a bool.
        assert!(out.contains("issues.isEmpty() } } catch (_: Exception) { false }"), "{out}");
    }
}
